# ============================================================
#  dev/gen-texts.ps1 - encode dev/texts.json as Base64 and inject it into
#  src-tauri/scripts/scan.ps1 (the TEXT-BLOCK region).
#
#  Why: Windows PowerShell 5.1 decodes a BOM-less script with the ANSI code page,
#  so Chinese literals inside the .ps1 would be corrupted (and can even swallow
#  newlines while parsing). Keeping the Chinese copy as Base64(UTF-8 JSON) makes
#  the script safe under both ANSI and UTF-8 decoding.
#
#  Usage: pwsh -NoProfile -File dev/gen-texts.ps1
#  After editing dev/texts.json this must be re-run for scan.ps1 to pick it up.
# ============================================================
param(
    [string]$Root = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'

$textsPath = Join-Path $Root 'dev/texts.json'
$scanPath = Join-Path $Root 'src-tauri/scripts/scan.ps1'

if (-not (Test-Path -LiteralPath $textsPath)) { throw "texts file not found: $textsPath" }
if (-not (Test-Path -LiteralPath $scanPath)) { throw "scan script not found: $scanPath" }

# 1. texts.json -> compact JSON -> UTF-8 -> Base64
$raw = [System.IO.File]::ReadAllText($textsPath, [System.Text.Encoding]::UTF8)
$obj = $raw | ConvertFrom-Json
$compact = ConvertTo-Json -InputObject $obj -Compress -Depth 12
$b64 = [Convert]::ToBase64String([System.Text.Encoding]::UTF8.GetBytes($compact))

# 2. wrap at 100 chars so diffs stay readable
$lines = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $b64.Length; $i += 100) {
    $len = [Math]::Min(100, $b64.Length - $i)
    $lines.Add($b64.Substring($i, $len))
}

$blockLines = New-Object System.Collections.Generic.List[string]
$blockLines.Add('# >>> TEXT-BLOCK-BEGIN (generated by dev/gen-texts.ps1 - do not edit; edit dev/texts.json then regenerate)')
$blockLines.Add('$script:TextB64 = @''')
foreach ($line in $lines) { $blockLines.Add($line) }
$blockLines.Add('''@')
$blockLines.Add('# <<< TEXT-BLOCK-END')
$block = ($blockLines -join "`r`n")

# 3. locate the markers and splice in the new block (plain text, no regex)
$src = [System.IO.File]::ReadAllText($scanPath, [System.Text.Encoding]::UTF8)
$beginTag = '# >>> TEXT-BLOCK-BEGIN'
$endTag = '# <<< TEXT-BLOCK-END'
$i = $src.IndexOf($beginTag, [StringComparison]::Ordinal)
$j = $src.IndexOf($endTag, [StringComparison]::Ordinal)
if ($i -lt 0 -or $j -lt $i) { throw 'TEXT-BLOCK markers not found in scan.ps1' }
$out = $src.Substring(0, $i) + $block + $src.Substring($j + $endTag.Length)

# 4. write back as UTF-8 without BOM (the Rust side prepends a BOM when materialising it)
[System.IO.File]::WriteAllText($scanPath, $out, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "OK: text block injected into $scanPath (JSON $($compact.Length) chars -> Base64 $($b64.Length) chars)"
