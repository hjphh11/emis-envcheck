# ---------- 16. security ----------
$security = [ordered]@{
    defenderRealtime = $null; antivirus = @(); firewall = $null
    secureBoot = $null; tpm = $null; uac = $null
}
$swSec = Start-Timer
try {
    # Antivirus list first (SecurityCenter2 is absent on Server builds).
    # Doing this before the Defender query also gives us `productState`, which encodes
    # real-time protection in its second byte -- a ~1 ms read that replaces a
    # 496-1743 ms Get-MpComputerStatus call on most machines.
    $avs = @()
    $avRealtime = $null
    $avList = @(Get-CimSafe -Class 'AntiVirusProduct' -Namespace 'root/SecurityCenter2' -TimeoutSec 4)
    foreach ($av in $avList) {
        if ($null -eq $av) { continue }
        $avName = Clean-Text $av.displayName
        if ($null -ne $avName) { $avs += $avName }
        # productState layout: 0x00PPSS. The middle byte carries the protection flags;
        # bit 0x10 means "real-time protection enabled". Only trust it for Defender,
        # because third-party AVs do not always follow the Windows Security convention.
        if ($null -eq $avRealtime -and $null -ne $avName -and $avName -match '(?i)defender') {
            $psRaw = To-LongOrNull $av.productState
            if ($null -ne $psRaw) {
                $stateByte = [int](($psRaw -shr 8) -band 0xFF)
                $avRealtime = (($stateByte -band 0x10) -ne 0)
            }
        }
    }
    $security.antivirus = $avs

    # Defender real-time protection.
    $security.defenderRealtime = $avRealtime
    if ($null -eq $security.defenderRealtime) {
        # Fall back to the Defender cmdlet only when productState was unusable.
        # (The old registry fallback read `DisableRealtimeMonitoring`, which modern
        # Windows 10/11 no longer stores, so it was dead code.)
        try {
            $mp = Get-MpComputerStatus -ErrorAction Stop
            if ($null -ne $mp -and $null -ne $mp.RealTimeProtectionEnabled) {
                $security.defenderRealtime = [bool]$mp.RealTimeProtectionEnabled
            }
        } catch { }
    }
    # Firewall: three registry profiles (much faster than Get-NetFirewallProfile).
    $fwStates = @{}
    foreach ($prof in @(@{ name = 'domain'; path = 'DomainProfile' }, @{ name = 'private'; path = 'StandardProfile' }, @{ name = 'public'; path = 'PublicProfile' })) {
        $en = Get-RegValue ('HKLM:\SYSTEM\CurrentControlSet\Services\SharedAccess\Parameters\FirewallPolicy\' + $prof.path) 'EnableFirewall'
        $stateText = $null
        if ($null -ne $en) {
            $enN = To-IntOrNull $en
            if ($null -ne $enN) {
                if ($enN -eq 1) { $stateText = [string]$script:T.status.on } else { $stateText = [string]$script:T.status.off }
            }
        }
        $fwStates[$prof.name] = $stateText
    }
    $domainState = $fwStates['domain']
    $privateState = $fwStates['private']
    $publicState = $fwStates['public']
    if ($null -ne $domainState -and $null -ne $privateState -and $null -ne $publicState) {
        if ($domainState -eq [string]$script:T.status.on -and $privateState -eq [string]$script:T.status.on -and $publicState -eq [string]$script:T.status.on) {
            $security.firewall = ($script:T.fmt.firewallAll -f [string]$script:T.status.on)
        } elseif ($domainState -eq [string]$script:T.status.off -and $privateState -eq [string]$script:T.status.off -and $publicState -eq [string]$script:T.status.off) {
            $security.firewall = ($script:T.fmt.firewallAll -f [string]$script:T.status.off)
        } else {
            $security.firewall = ($script:T.fmt.firewallMixed -f $domainState, $privateState, $publicState)
        }
    }
    # Secure Boot / TPM
    $security.secureBoot = $script:SecureBoot
    if ($null -eq $security.secureBoot -and $script:FirmwareMode -eq 'Legacy') { $security.secureBoot = $false }
    if ($null -ne $script:TpmFacts.version) {
        $security.tpm = [string]$script:TpmFacts.version
    } elseif ($script:TpmFacts.enabled -eq $false) {
        $security.tpm = [string]$script:T.fmt.noTpm
    }
    # UAC
    $uacLua = To-IntOrNull (Get-RegValue 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System' 'EnableLUA')
    $uacConsent = To-IntOrNull (Get-RegValue 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System' 'ConsentPromptBehaviorAdmin')
    if ($null -ne $uacLua) {
        if ($uacLua -eq 0) { $security.uac = [string]$script:T.fmt.uacOff }
        elseif ($uacConsent -eq 0) { $security.uac = [string]$script:T.fmt.uacOnNoPrompt }
        else { $security.uac = [string]$script:T.fmt.uacOn }
    }
} catch {
    Add-SectionFailure 'security' $_.Exception.Message
}
Stop-Timer 'security' $swSec

# ---------- 17. Collect activation result (background runspace) ----------
$activation = $null
try {
    if ($null -ne $script:ActivationHandle) {
        $elapsedMs = [int]$script:TotalSw.ElapsedMilliseconds
        $remaining = 8000 - $elapsedMs
        if ($remaining -lt 200) { $remaining = 200 }
        $waitMs = [int][Math]::Min(2500, $remaining)
        if ($script:ActivationHandle.AsyncWaitHandle.WaitOne($waitMs)) {
            $actOut = @($script:ActivationPs.EndInvoke($script:ActivationHandle))
            if ($actOut.Count -gt 0) { $activation = $actOut[0] }
        } else {
            Add-Warn ($script:T.warnings.activationFailed -f 'timeout')
            try { [void]$script:ActivationPs.BeginStop($null, $null) } catch { }
        }
    }
} catch {
    Add-Warn ($script:T.warnings.activationFailed -f [string]$_.Exception.Message)
}
if ($null -ne $activation) {
    $licStatus = To-IntOrNull $activation.status
    if ($null -ne $licStatus) {
        if ($licStatus -eq 1) { $system.activation = [string]$script:T.status.activated }
        elseif ($licStatus -eq 0 -or $licStatus -eq 5) { $system.activation = [string]$script:T.status.notActivated }
        elseif ($licStatus -eq 2 -or $licStatus -eq 3 -or $licStatus -eq 6) { $system.activation = [string]$script:T.status.grace }
        else { $system.activation = [string]$script:T.status.unknown }
    } else {
        $system.activation = [string]$script:T.status.unknown
        Add-Warn ([string]$script:T.warnings.activationUnknown)
    }
    $channel = [string]$activation.channel
    if ($channel -match '(?i)oem') { $system.activationType = 'OEM' }
    elseif ($channel -match '(?i)retail') { $system.activationType = 'Retail' }
    elseif ($channel -match '(?i)volume') { $system.activationType = 'Volume' }
    elseif (-not [string]::IsNullOrWhiteSpace($channel)) { $system.activationType = $channel }
}

# ---------- 18. compat (Windows 11 compatibility checks, tab C) ----------
$compatItems = @()
$swSec = Start-Timer
try {
    $C = $script:T.compat
    # Shared values used by several checks.
    $osBuildNum = To-IntOrNull $system.build
    $physicalCores = $cpu.physicalCores
    $cpuMhz = $cpu.baseMhz
    $memTotal = $memory.totalBytes
    $sysVolume = $null
    foreach ($ld in $logicalDisksRaw) {
        if ($null -ne $ld -and [string]$ld.DeviceID -eq [string]$env:SystemDrive) { $sysVolume = $ld; break }
    }
    $sysVolumeFree = $null
    $sysVolumeTotal = $null
    if ($null -ne $sysVolume) {
        $sysVolumeFree = To-LongOrNull $sysVolume.FreeSpace
        $sysVolumeTotal = To-LongOrNull $sysVolume.Size
    }
    $systemDiskStyle = $null
    foreach ($md in $msftDisks) {
        if ($null -eq $md) { continue }
        if ($md.IsSystem -eq $true -or $md.IsBoot -eq $true) {
            $st = [string]$md.PartitionStyle
            if ($st -match '(?i)gpt') { $systemDiskStyle = 'GPT' }
            elseif ($st -match '(?i)mbr') { $systemDiskStyle = 'MBR' }
            elseif ($st -match '(?i)raw') { $systemDiskStyle = 'RAW' }
            else {
                $stn = To-IntOrNull $md.PartitionStyle
                if ($stn -eq 2) { $systemDiskStyle = 'GPT' }
                elseif ($stn -eq 1) { $systemDiskStyle = 'MBR' }
            }
            break
        }
    }
    # 1) 64-bit CPU
    if ($null -ne $cpu.arch) {
        if ($cpu.arch -eq 'x64' -or $cpu.arch -eq 'ARM64') {
            $compatItems += [ordered]@{ id = 'c.arch.cpu64'; name = [string]$C.cpu64.name; status = 'pass'; actual = ($script:T.fmt.bit64 -f $cpu.arch); requirement = [string]$C.cpu64.requirement; reason = $null; detail = [string]$C.cpu64.passDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.arch.cpu64'; name = [string]$C.cpu64.name; status = 'fail'; actual = [string]$script:T.fmt.bit32; requirement = [string]$C.cpu64.requirement; reason = [string]$C.cpu64.failReason; detail = [string]$C.cpu64.failDetail }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.arch.cpu64'; name = [string]$C.cpu64.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.cpu64.requirement; reason = [string]$C.cpu64.unknownReason; detail = $null }
    }
    # 2) CPU model against the Win11 supported generations
    $cpuBrand = [string]$cpu.brand
    $modelStatus = 'warn'
    $modelReason = [string]$C.cpuModel.warnReason
    $modelDetail = [string]$C.cpuModel.warnDetail
    $intelGen = $null
    if ($cpuBrand -match '(?i)core\s*ultra') {
        $modelStatus = 'pass'; $modelReason = $null; $modelDetail = [string]$C.cpuModel.passDetail
    } elseif ($cpuBrand -match '(?i)i[3579]\s*-?\s*(\d{4,5})') {
        $numStr = $matches[1]
        # Intel model-number -> generation rules (this was mis-parsed once; keep it explicit):
        #   5 digits      : first two digits   14650 -> 14, 13900 -> 13
        #   4 digits, '1' : first two digits   1255 -> 12, 1135 -> 11, 1065 -> 10
        #                   (10th-13th gen U/G SKUs are 4-digit. Taking only the first digit
        #                    turned 1255 into gen 1, so supported 12/13th gen laptops got
        #                    fail -> verdict=blocked. That was a false positive.)
        #   4 digits, else: first digit        8550 -> 8, 9750 -> 9
        if ($numStr.Length -ge 5) {
            $intelGen = [int]$numStr.Substring(0, 2)
        } elseif ($numStr.Length -eq 4) {
            if ($numStr.Substring(0, 1) -eq '1') { $intelGen = [int]$numStr.Substring(0, 2) }
            else { $intelGen = [int]$numStr.Substring(0, 1) }
        }
        if ($null -ne $intelGen) {
            if ($intelGen -ge 8) { $modelStatus = 'pass'; $modelReason = $null; $modelDetail = [string]$C.cpuModel.passDetail }
            else { $modelStatus = 'fail'; $modelReason = [string]$C.cpuModel.failReason; $modelDetail = [string]$C.cpuModel.failDetail }
        }
    } elseif ($cpuBrand -match '(?i)(pentium|celeron|atom)') {
        $modelStatus = 'warn'
    } elseif ($cpuBrand -match '(?i)ryzen\s*ai') {
        $modelStatus = 'pass'; $modelReason = $null; $modelDetail = [string]$C.cpuModel.passDetail
    } elseif ($cpuBrand -match '(?i)ryzen') {
        if ($cpuBrand -match '(\d{4})') {
            $rFirst = [int]([string]([int]$matches[1])).Substring(0, 1)
            if ($rFirst -ge 2) { $modelStatus = 'pass'; $modelReason = $null; $modelDetail = [string]$C.cpuModel.passDetail }
            else { $modelStatus = 'fail'; $modelReason = [string]$C.cpuModel.failReason; $modelDetail = [string]$C.cpuModel.failDetail }
        }
    } elseif ($cpuBrand -match '(?i)xeon|athlon|sempron') {
        $modelStatus = 'warn'
    }
    $compatItems += [ordered]@{ id = 'c.cpu.model'; name = [string]$C.cpuModel.name; status = $modelStatus; actual = $cpuBrand; requirement = [string]$C.cpuModel.requirement; reason = $modelReason; detail = $modelDetail }
    # 3) Core count
    if ($null -ne $physicalCores) {
        if ($physicalCores -ge 2) {
            $actualCores = ($script:T.fmt.coresOnly -f [string]$physicalCores)
            if ($null -ne $cpu.logicalCores) { $actualCores = ($script:T.fmt.coresThreads -f [string]$physicalCores, [string]$cpu.logicalCores) }
            $compatItems += [ordered]@{ id = 'c.cpu.cores'; name = [string]$C.cpuCores.name; status = 'pass'; actual = $actualCores; requirement = [string]$C.cpuCores.requirement; reason = $null; detail = [string]$C.cpuCores.passDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.cpu.cores'; name = [string]$C.cpuCores.name; status = 'fail'; actual = ($script:T.fmt.coresOnly -f [string]$physicalCores); requirement = [string]$C.cpuCores.requirement; reason = [string]$C.cpuCores.failReason; detail = [string]$C.cpuCores.failDetail }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.cpu.cores'; name = [string]$C.cpuCores.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.cpuCores.requirement; reason = [string]$C.cpuCores.unknownReason; detail = $null }
    }
    # 4) Clock speed
    if ($null -ne $cpuMhz) {
        if ($cpuMhz -ge 1000) {
            $compatItems += [ordered]@{ id = 'c.cpu.clock'; name = [string]$C.cpuClock.name; status = 'pass'; actual = ($script:T.fmt.mhz -f [string]$cpuMhz); requirement = [string]$C.cpuClock.requirement; reason = $null; detail = [string]$C.cpuClock.passDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.cpu.clock'; name = [string]$C.cpuClock.name; status = 'fail'; actual = ($script:T.fmt.mhz -f [string]$cpuMhz); requirement = [string]$C.cpuClock.requirement; reason = [string]$C.cpuClock.failReason; detail = [string]$C.cpuClock.failDetail }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.cpu.clock'; name = [string]$C.cpuClock.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.cpuClock.requirement; reason = $null; detail = $null }
    }
    # 5) Memory
    if ($null -ne $memTotal -and $memTotal -gt 0) {
        $memGbInt = [int][Math]::Round($memTotal / 1073741824.0)
        if ($memGbInt -ge 4) {
            $memDetail = [string]$C.memSize.passDetail
            if ($memGbInt -lt 8) { $memDetail = [string]$C.memSize.warnReason }
            $compatItems += [ordered]@{ id = 'c.mem.size'; name = [string]$C.memSize.name; status = 'pass'; actual = ($script:T.fmt.gb -f [string]$memGbInt); requirement = [string]$C.memSize.requirement; reason = $null; detail = $memDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.mem.size'; name = [string]$C.memSize.name; status = 'fail'; actual = ($script:T.fmt.gb -f [string]$memGbInt); requirement = [string]$C.memSize.requirement; reason = [string]$C.memSize.failReason; detail = [string]$C.memSize.failDetail }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.mem.size'; name = [string]$C.memSize.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.memSize.requirement; reason = [string]$C.memSize.unknownReason; detail = $null }
    }
    # 6) System drive capacity + free space
    # Windows 11 requires DEVICE CAPACITY >= 64 GB, not FREE SPACE >= 64 GB.
    # Comparing free space against 64 GB flagged healthy Win11 machines as fail ->
    # verdict=blocked (measured: 300 GB total / 57.5 GB free was reported as
    # "cannot upgrade"). Split into two dimensions:
    #   capacity < 64 GB                    -> fail
    #   capacity ok but free space < 20 GB  -> warn (does NOT contribute to blocked)
    if ($null -ne $sysVolumeFree -and $null -ne $sysVolumeTotal) {
        $freeGb = [Math]::Round($sysVolumeFree / 1073741824.0, 1)
        $totalGb = [Math]::Round($sysVolumeTotal / 1073741824.0, 1)
        $actualSpace = ($script:T.fmt.diskAvail -f [string]$freeGb, [string]$totalGb)
        if ($totalGb -lt 64) {
            $compatItems += [ordered]@{ id = 'c.disk.space'; name = [string]$C.diskSpace.name; status = 'fail'; actual = $actualSpace; requirement = [string]$C.diskSpace.requirement; reason = [string]$C.diskSpace.failReason; detail = [string]$C.diskSpace.failDetail }
        } elseif ($freeGb -lt 20) {
            $compatItems += [ordered]@{ id = 'c.disk.space'; name = [string]$C.diskSpace.name; status = 'warn'; actual = $actualSpace; requirement = [string]$C.diskSpace.requirement; reason = [string]$C.diskSpace.warnReason; detail = [string]$C.diskSpace.warnDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.disk.space'; name = [string]$C.diskSpace.name; status = 'pass'; actual = $actualSpace; requirement = [string]$C.diskSpace.requirement; reason = $null; detail = [string]$C.diskSpace.passDetail }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.disk.space'; name = [string]$C.diskSpace.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.diskSpace.requirement; reason = [string]$C.diskSpace.unknownReason; detail = $null }
    }
    # 7) UEFI
    if ($script:FirmwareMode -eq 'UEFI') {
        $compatItems += [ordered]@{ id = 'c.fw.uefi'; name = [string]$C.uefi.name; status = 'pass'; actual = 'UEFI'; requirement = [string]$C.uefi.requirement; reason = $null; detail = [string]$C.uefi.passDetail }
    } elseif ($script:FirmwareMode -eq 'Legacy') {
        $compatItems += [ordered]@{ id = 'c.fw.uefi'; name = [string]$C.uefi.name; status = 'fail'; actual = 'Legacy BIOS'; requirement = [string]$C.uefi.requirement; reason = [string]$C.uefi.failReason; detail = [string]$C.uefi.failDetail }
    } else {
        $compatItems += [ordered]@{ id = 'c.fw.uefi'; name = [string]$C.uefi.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.uefi.requirement; reason = [string]$C.uefi.unknownReason; detail = $null }
    }
    # 8) Secure Boot
    if ($null -ne $script:SecureBoot) {
        if ($script:SecureBoot -eq $true) {
            $compatItems += [ordered]@{ id = 'c.fw.secureboot'; name = [string]$C.secureBoot.name; status = 'pass'; actual = [string]$script:T.fmt.enabled; requirement = [string]$C.secureBoot.requirement; reason = $null; detail = [string]$C.secureBoot.passDetail }
        } elseif ($script:FirmwareMode -eq 'UEFI') {
            $compatItems += [ordered]@{ id = 'c.fw.secureboot'; name = [string]$C.secureBoot.name; status = 'warn'; actual = [string]$script:T.fmt.disabled; requirement = [string]$C.secureBoot.requirement; reason = [string]$C.secureBoot.warnReason; detail = [string]$C.secureBoot.warnDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.fw.secureboot'; name = [string]$C.secureBoot.name; status = 'fail'; actual = [string]$script:T.status.unsupported; requirement = [string]$C.secureBoot.requirement; reason = [string]$C.secureBoot.failReason; detail = $null }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.fw.secureboot'; name = [string]$C.secureBoot.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.secureBoot.requirement; reason = [string]$C.secureBoot.unknownReason; detail = $null }
    }
    # 9) TPM
    $tpmVer = [string]$script:TpmFacts.version
    if ($tpmVer -eq '2.0') {
        $compatItems += [ordered]@{ id = 'c.fw.tpm'; name = [string]$C.tpm.name; status = 'pass'; actual = ($script:T.fmt.tpmVersion -f '2.0'); requirement = [string]$C.tpm.requirement; reason = $null; detail = [string]$C.tpm.passDetail }
    } elseif ($tpmVer -eq '1.2') {
        $compatItems += [ordered]@{ id = 'c.fw.tpm'; name = [string]$C.tpm.name; status = 'fail'; actual = ($script:T.fmt.tpmVersion -f '1.2'); requirement = [string]$C.tpm.requirement; reason = [string]$C.tpm.failReason; detail = [string]$C.tpm.failDetail }
    } elseif ($null -eq $script:TpmFacts.enabled) {
        $compatItems += [ordered]@{ id = 'c.fw.tpm'; name = [string]$C.tpm.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.tpm.requirement; reason = [string]$C.tpm.unknownReason; detail = $null }
    } elseif ($script:TpmFacts.enabled -eq $false) {
        $compatItems += [ordered]@{ id = 'c.fw.tpm'; name = [string]$C.tpm.name; status = 'warn'; actual = [string]$script:T.fmt.noTpm; requirement = [string]$C.tpm.requirement; reason = [string]$C.tpm.warnDisabled; detail = [string]$C.tpm.failDetail }
    } elseif ($null -eq $tpmVer) {
        # A TPM device exists (enabled=true) but its version could not be read
        # (standard user + Get-Tpm unavailable -> version intentionally left null).
        # This must be UNKNOWN, not fail: reporting "no TPM detected" while
        # motherboard.tpmEnabled=true is self-contradictory inside one JSON payload.
        $compatItems += [ordered]@{ id = 'c.fw.tpm'; name = [string]$C.tpm.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.tpm.requirement; reason = [string]$C.tpm.unknownReason; detail = $null }
    } else {
        $compatItems += [ordered]@{ id = 'c.fw.tpm'; name = [string]$C.tpm.name; status = 'fail'; actual = [string]$script:T.fmt.noTpm; requirement = [string]$C.tpm.requirement; reason = [string]$C.tpm.failReasonMissing; detail = [string]$C.tpm.failDetail }
    }
    # 10) DirectX 12
    $dxInfo = $runtime.directx
    if ($null -ne $dxInfo.featureLevel) {
        if ([int]$dxInfo.major -ge 12) {
            $compatItems += [ordered]@{ id = 'c.gfx.dx12'; name = [string]$C.dx12.name; status = 'pass'; actual = ($script:T.fmt.featureLevel -f [string]$dxInfo.featureLevel); requirement = [string]$C.dx12.requirement; reason = $null; detail = [string]$C.dx12.passDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.gfx.dx12'; name = [string]$C.dx12.name; status = 'fail'; actual = ($script:T.fmt.featureLevel -f [string]$dxInfo.featureLevel); requirement = [string]$C.dx12.requirement; reason = [string]$C.dx12.failReason; detail = [string]$C.dx12.failDetail }
        }
    } elseif ($dxInfo.d3d12 -eq $true) {
        $compatItems += [ordered]@{ id = 'c.gfx.dx12'; name = [string]$C.dx12.name; status = 'pass'; actual = [string]$script:T.fmt.supported; requirement = [string]$C.dx12.requirement; reason = $null; detail = [string]$C.dx12.passDetail }
    } elseif ($dxInfo.d3d12 -eq $false) {
        $compatItems += [ordered]@{ id = 'c.gfx.dx12'; name = [string]$C.dx12.name; status = 'fail'; actual = [string]$script:T.fmt.unsupported; requirement = [string]$C.dx12.requirement; reason = [string]$C.dx12.failReason; detail = [string]$C.dx12.failDetail }
    } else {
        $compatItems += [ordered]@{ id = 'c.gfx.dx12'; name = [string]$C.dx12.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.dx12.requirement; reason = [string]$C.dx12.unknownReason; detail = $null }
    }
    # 11) WDDM 2.0 (inferred from DX12 feature level when the registry has no version)
    $wddmVer = [string]$dxInfo.wddm
    if (-not [string]::IsNullOrWhiteSpace($wddmVer)) {
        $wddmMajor = 0
        if ($wddmVer -match '(\d+)\.') { $wddmMajor = [int]$matches[1] }
        if ($wddmMajor -ge 2) {
            $compatItems += [ordered]@{ id = 'c.gfx.wddm'; name = [string]$C.wddm.name; status = 'pass'; actual = ($script:T.fmt.wddmVersion -f $wddmVer); requirement = [string]$C.wddm.requirement; reason = $null; detail = [string]$C.wddm.passDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.gfx.wddm'; name = [string]$C.wddm.name; status = 'fail'; actual = ($script:T.fmt.wddmVersion -f $wddmVer); requirement = [string]$C.wddm.requirement; reason = [string]$C.wddm.failReason; detail = [string]$C.wddm.failDetail }
        }
    } elseif ($null -ne $dxInfo.featureLevel -and [int]$dxInfo.major -ge 12) {
        $compatItems += [ordered]@{ id = 'c.gfx.wddm'; name = [string]$C.wddm.name; status = 'pass'; actual = [string]$script:T.fmt.wddmInferred; requirement = [string]$C.wddm.requirement; reason = $null; detail = [string]$C.wddm.passDetail }
    } else {
        $compatItems += [ordered]@{ id = 'c.gfx.wddm'; name = [string]$C.wddm.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.wddm.requirement; reason = [string]$C.wddm.unknownReason; detail = $null }
    }
    # 12) Display
    $primaryDisplay = $null
    foreach ($dp in $displays) {
        if ($dp.primary -eq $true) { $primaryDisplay = $dp; break }
    }
    if ($null -ne $primaryDisplay) {
        $resW = $null
        $resH = $null
        if ($null -ne $primaryDisplay.resolution -and $primaryDisplay.resolution -match '^(\d+)x(\d+)$') {
            $resW = [int]$matches[1]
            $resH = [int]$matches[2]
        }
        $sizeOk = ($null -eq $primaryDisplay.sizeInch -or $primaryDisplay.sizeInch -ge 9)
        $resOk = ($null -ne $resW -and $null -ne $resH -and $resW -ge 1280 -and $resH -ge 720)
        $actualDisp = $null
        if ($null -ne $resW -and $null -ne $resH) { $actualDisp = ($script:T.fmt.resOnly -f [string]$resW, [string]$resH) }
        if ($null -ne $primaryDisplay.sizeInch) {
            if ($null -ne $resW -and $null -ne $resH) { $actualDisp = ($script:T.fmt.resWithSize -f [string]$primaryDisplay.sizeInch, [string]$resW, [string]$resH) }
            else { $actualDisp = ($script:T.fmt.inch -f [string]$primaryDisplay.sizeInch) }
        }
        if ($null -eq $actualDisp) { $actualDisp = [string]$script:T.fmt.noData }
        if ($sizeOk -and $resOk) {
            $compatItems += [ordered]@{ id = 'c.display.basic'; name = [string]$C.display.name; status = 'pass'; actual = $actualDisp; requirement = [string]$C.display.requirement; reason = $null; detail = [string]$C.display.passDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.display.basic'; name = [string]$C.display.name; status = 'warn'; actual = $actualDisp; requirement = [string]$C.display.requirement; reason = [string]$C.display.warnReason; detail = $null }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.display.basic'; name = [string]$C.display.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.display.requirement; reason = [string]$C.display.unknownReason; detail = $null }
    }
    # 13) SSE4.2 / POPCNT
    $hasSSE42 = $null
    if ($cpu.instructions -contains 'SSE4.2') { $hasSSE42 = $true }
    elseif ($script:CpuFeaturesOk -eq $true) { $hasSSE42 = $false }
    if ($hasSSE42 -eq $true) {
        $compatItems += [ordered]@{ id = 'c.cpu.sse42'; name = [string]$C.sse42.name; status = 'pass'; actual = [string]$script:T.fmt.supported; requirement = [string]$C.sse42.requirement; reason = $null; detail = [string]$C.sse42.passDetail }
    } elseif ($hasSSE42 -eq $false) {
        $compatItems += [ordered]@{ id = 'c.cpu.sse42'; name = [string]$C.sse42.name; status = 'fail'; actual = [string]$script:T.fmt.unsupported; requirement = [string]$C.sse42.requirement; reason = [string]$C.sse42.failReason; detail = $null }
    } else {
        $compatItems += [ordered]@{ id = 'c.cpu.sse42'; name = [string]$C.sse42.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.sse42.requirement; reason = [string]$C.sse42.unknownReason; detail = $null }
    }
    # 14) System disk partition style
    if ($null -ne $systemDiskStyle) {
        if ($systemDiskStyle -eq 'GPT') {
            $compatItems += [ordered]@{ id = 'c.disk.gpt'; name = [string]$C.gpt.name; status = 'pass'; actual = 'GPT'; requirement = [string]$C.gpt.requirement; reason = $null; detail = [string]$C.gpt.passDetail }
        } elseif ($systemDiskStyle -eq 'MBR') {
            $compatItems += [ordered]@{ id = 'c.disk.gpt'; name = [string]$C.gpt.name; status = 'warn'; actual = 'MBR'; requirement = [string]$C.gpt.requirement; reason = [string]$C.gpt.warnReason; detail = [string]$C.gpt.warnDetail }
        } else {
            $compatItems += [ordered]@{ id = 'c.disk.gpt'; name = [string]$C.gpt.name; status = 'unknown'; actual = $systemDiskStyle; requirement = [string]$C.gpt.requirement; reason = [string]$C.gpt.unknownReason; detail = $null }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.disk.gpt'; name = [string]$C.gpt.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.gpt.requirement; reason = [string]$C.gpt.unknownReason; detail = $null }
    }
    # 15) OS version
    if ($null -ne $osBuildNum) {
        if ($osBuildNum -ge 22000) {
            $compatItems += [ordered]@{ id = 'c.os.version'; name = [string]$C.osVersion.name; status = 'pass'; actual = ($script:T.fmt.osWin11 -f [string]$osBuildNum); requirement = [string]$C.osVersion.requirement; reason = $null; detail = [string]$C.osVersion.passDetail }
        } elseif ($osBuildNum -ge 19041) {
            $compatItems += [ordered]@{ id = 'c.os.version'; name = [string]$C.osVersion.name; status = 'warn'; actual = ($script:T.fmt.osWin10 -f [string]$osBuildNum); requirement = [string]$C.osVersion.requirement; reason = [string]$C.osVersion.warnReason; detail = $null }
        } else {
            $compatItems += [ordered]@{ id = 'c.os.version'; name = [string]$C.osVersion.name; status = 'fail'; actual = ($script:T.fmt.osOther -f [string]$osBuildNum); requirement = [string]$C.osVersion.requirement; reason = [string]$C.osVersion.failReason; detail = [string]$C.osVersion.failDetail }
        }
    } else {
        $compatItems += [ordered]@{ id = 'c.os.version'; name = [string]$C.osVersion.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$C.osVersion.requirement; reason = [string]$C.osVersion.unknownReason; detail = $null }
    }
    # 16) GPU driver installed and WDDM >= 2.0 (prefer the discrete GPU when there are several)
    $primaryGpu = $null
    foreach ($gpuItem in $gpus) {
        if ($null -ne $gpuItem -and $gpuItem.discrete -eq $true) { $primaryGpu = $gpuItem; break }
    }
    if ($null -eq $primaryGpu -and $gpus.Count -gt 0) { $primaryGpu = $gpus[0] }
    $gpuDriverInfo = $C.gpuDriver
    $gpuAgeInfo = $C.gpuDriverAge
    $driverDateText = $null
    $driverAgeMonths = $null
    if ($null -ne $primaryGpu) {
        if ($null -ne $primaryGpu.driverDate -and ([string]$primaryGpu.driverDate) -match '^(\d{4}-\d{2}-\d{2})') {
            $driverDateText = $matches[1]
            try {
                $driverDateValue = [datetime]::Parse($driverDateText, [System.Globalization.CultureInfo]::InvariantCulture)
                $driverAgeMonths = [int][Math]::Floor(((Get-Date) - $driverDateValue).TotalDays / 30.44)
                if ($driverAgeMonths -lt 0) { $driverAgeMonths = 0 }
            } catch { }
        }
        $driverVersionText = [string]$primaryGpu.driverVersion
        $gpuVendorText = [string]$primaryGpu.vendor
        if ([string]::IsNullOrWhiteSpace($gpuVendorText)) { $gpuVendorText = [string]$primaryGpu.name }
        $driverActual = $null
        if (-not [string]::IsNullOrWhiteSpace($driverVersionText)) {
            $driverActual = ($gpuVendorText + ' ' + $driverVersionText).Trim()
            if ($null -ne $driverDateText) { $driverActual = $driverActual + ' / ' + $driverDateText }
        }
        # WDDM: use the real version when readable, otherwise infer from the DX12 feature level.
        $wddmKnownText = [string]$runtime.directx.wddm
        $wddmOk = $false
        $wddmInferred = $false
        if (-not [string]::IsNullOrWhiteSpace($wddmKnownText)) {
            if ($wddmKnownText -match '^(\d+)\.') {
                if ([int]$matches[1] -ge 2) { $wddmOk = $true }
            }
        } elseif ($null -ne $runtime.directx.featureLevel -and $null -ne $runtime.directx.major -and [int]$runtime.directx.major -ge 12) {
            $wddmOk = $true
            $wddmInferred = $true
        }
        $gpuStatusText = [string]$primaryGpu.status
        if ([string]::IsNullOrWhiteSpace($driverVersionText)) {
            if (-not [string]::IsNullOrWhiteSpace($gpuStatusText) -and $gpuStatusText -ne 'OK') {
                $compatItems += [ordered]@{ id = 'gpu.driver'; name = [string]$gpuDriverInfo.name; status = 'fail'; actual = $gpuStatusText; requirement = [string]$gpuDriverInfo.requirement; reason = [string]$gpuDriverInfo.failReason; detail = [string]$gpuDriverInfo.failDetail }
            } else {
                $compatItems += [ordered]@{ id = 'gpu.driver'; name = [string]$gpuDriverInfo.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$gpuDriverInfo.requirement; reason = [string]$gpuDriverInfo.unknownReason; detail = $null }
            }
        } elseif (-not [string]::IsNullOrWhiteSpace($gpuStatusText) -and $gpuStatusText -ne 'OK') {
            $compatItems += [ordered]@{ id = 'gpu.driver'; name = [string]$gpuDriverInfo.name; status = 'fail'; actual = $driverActual; requirement = [string]$gpuDriverInfo.requirement; reason = [string]$gpuDriverInfo.failReason; detail = [string]$gpuDriverInfo.failDetail }
        } elseif ($wddmOk) {
            $driverDetail = [string]$gpuDriverInfo.passDetail
            if ($wddmInferred) { $driverDetail = $driverDetail + [string]$gpuDriverInfo.wddmInferred }
            $compatItems += [ordered]@{ id = 'gpu.driver'; name = [string]$gpuDriverInfo.name; status = 'pass'; actual = $driverActual; requirement = [string]$gpuDriverInfo.requirement; reason = $null; detail = $driverDetail }
        } else {
            $compatItems += [ordered]@{ id = 'gpu.driver'; name = [string]$gpuDriverInfo.name; status = 'unknown'; actual = $driverActual; requirement = [string]$gpuDriverInfo.requirement; reason = [string]$gpuDriverInfo.unknownReason; detail = $null }
        }
        # 17) GPU driver age: older than 18 months => warn
        if ($null -eq $driverDateText) {
            $compatItems += [ordered]@{ id = 'gpu.driverAge'; name = [string]$gpuAgeInfo.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$gpuAgeInfo.requirement; reason = [string]$gpuAgeInfo.unknownReason; detail = $null }
        } elseif ($null -ne $driverAgeMonths) {
            $ageActual = ($script:T.fmt.driverDateMonths -f $driverDateText, [string]$driverAgeMonths)
            if ($driverAgeMonths -gt 18) {
                $compatItems += [ordered]@{ id = 'gpu.driverAge'; name = [string]$gpuAgeInfo.name; status = 'warn'; actual = $ageActual; requirement = [string]$gpuAgeInfo.requirement; reason = ($gpuAgeInfo.warnReason -f [string]$driverAgeMonths); detail = [string]$gpuAgeInfo.warnDetail }
            } else {
                $compatItems += [ordered]@{ id = 'gpu.driverAge'; name = [string]$gpuAgeInfo.name; status = 'pass'; actual = $ageActual; requirement = [string]$gpuAgeInfo.requirement; reason = $null; detail = [string]$gpuAgeInfo.passDetail }
            }
        } else {
            $compatItems += [ordered]@{ id = 'gpu.driverAge'; name = [string]$gpuAgeInfo.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$gpuAgeInfo.requirement; reason = [string]$gpuAgeInfo.unknownReason; detail = $null }
        }
    } else {
        $compatItems += [ordered]@{ id = 'gpu.driver'; name = [string]$gpuDriverInfo.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$gpuDriverInfo.requirement; reason = [string]$gpuDriverInfo.unknownReason; detail = $null }
        $compatItems += [ordered]@{ id = 'gpu.driverAge'; name = [string]$gpuAgeInfo.name; status = 'unknown'; actual = [string]$script:T.fmt.noData; requirement = [string]$gpuAgeInfo.requirement; reason = [string]$gpuAgeInfo.unknownReason; detail = $null }
    }
} catch {
    Add-SectionFailure 'compat' $_.Exception.Message
}
Stop-Timer 'compat' $swSec

$passCount = 0
$warnCount = 0
$failCount = 0
$unknownCount = 0
foreach ($ci in $compatItems) {
    switch ([string]$ci.status) {
        'pass' { $passCount++ }
        'warn' { $warnCount++ }
        'fail' { $failCount++ }
        default { $unknownCount++ }
    }
}
$verdict = 'ok'
if ($failCount -gt 0) { $verdict = 'blocked' }
elseif ($warnCount -gt 0) { $verdict = 'warn' }
$compat = [ordered]@{
    verdict      = $verdict
    passCount    = $passCount
    warnCount    = $warnCount
    failCount    = $failCount
    unknownCount = $unknownCount
    items        = $compatItems
}

# ---------- 19. score (health score) ----------
$scoreParts = @()
$swSec = Start-Timer
try {
    # CPU
    $cpuScore = 30
    $phys = $cpu.physicalCores
    $logi = $cpu.logicalCores
    if ($null -ne $phys) {
        if ($phys -ge 16) { $cpuScore += 32 }
        elseif ($phys -ge 12) { $cpuScore += 28 }
        elseif ($phys -ge 8) { $cpuScore += 24 }
        elseif ($phys -ge 6) { $cpuScore += 18 }
        elseif ($phys -ge 4) { $cpuScore += 12 }
        elseif ($phys -ge 2) { $cpuScore += 6 }
    }
    if ($null -ne $logi) {
        if ($logi -ge 32) { $cpuScore += 12 }
        elseif ($logi -ge 16) { $cpuScore += 10 }
        elseif ($logi -ge 8) { $cpuScore += 6 }
        elseif ($logi -ge 4) { $cpuScore += 3 }
    }
    if ($null -ne $intelGen) {
        if ($intelGen -ge 12) { $cpuScore += 14 }
        elseif ($intelGen -ge 10) { $cpuScore += 11 }
        elseif ($intelGen -ge 8) { $cpuScore += 8 }
    } elseif ($cpuBrand -match '(?i)ryzen') {
        if ($cpuBrand -match '(\d{4})') {
            $rFirst = [int]([string]([int]$matches[1])).Substring(0, 1)
            if ($rFirst -ge 7) { $cpuScore += 14 }
            elseif ($rFirst -ge 5) { $cpuScore += 12 }
            elseif ($rFirst -ge 3) { $cpuScore += 10 }
        }
    }
    if ($null -ne $cpuMhz) {
        if ($cpuMhz -ge 3200) { $cpuScore += 8 }
        elseif ($cpuMhz -ge 2400) { $cpuScore += 6 }
        elseif ($cpuMhz -ge 1800) { $cpuScore += 4 }
        elseif ($cpuMhz -ge 1000) { $cpuScore += 2 }
    }
    if ($null -ne $cpu.usagePct -and $cpu.usagePct -ge 90) { $cpuScore -= 5 }
    $cpuScore = Clamp-Score $cpuScore
    $cpuSeries = [string]$script:T.fmt.cpuSeriesOther
    if ($null -ne $intelGen) { $cpuSeries = ($script:T.fmt.cpuSeriesIntel -f [string]$intelGen) }
    elseif ($cpuBrand -match '(?i)ryzen') {
        if ($cpuBrand -match '(\d)\d{3}') { $cpuSeries = ($script:T.fmt.cpuSeriesAmd -f $matches[1]) }
        else { $cpuSeries = [string]$script:T.fmt.cpuSeriesAmdGeneric }
    }
    $cpuNote = ''
    if ($null -ne $phys -and $null -ne $logi -and $null -ne $cpuMhz) {
        $cpuNote = ($script:T.score.notes.cpu -f [string]$phys, [string]$logi, $cpuSeries, [string]$cpuMhz)
    } elseif ($null -ne $phys) {
        $cpuNote = ($script:T.score.notes.cpuGeneric -f [string]$phys, [string]$logi, [string]$cpuMhz)
    } else {
        $cpuNote = [string]$cpuBrand
    }
    $scoreParts += [ordered]@{ key = 'cpu'; label = [string]$script:T.labels.cpu; score = $cpuScore; weight = 0.25; note = $cpuNote }

    # Memory
    $memScore = 20
    if ($memTotal -gt 0) {
        $memGbInt = [int][Math]::Round($memTotal / 1073741824.0)
        if ($memGbInt -ge 32) { $memScore = 100 }
        elseif ($memGbInt -ge 16) { $memScore = 90 }
        elseif ($memGbInt -ge 8) { $memScore = 72 }
        elseif ($memGbInt -ge 4) { $memScore = 45 }
        else { $memScore = 20 }
        if ($memory.usedPct -ge 90) { $memScore -= 10 }
        $memScore = Clamp-Score $memScore
    }
    $memType = ''
    if ($memory.modules.Count -gt 0 -and $null -ne $memory.modules[0].type) { $memType = [string]$memory.modules[0].type }
    $channelText = [string]$script:T.labels.singleChannel
    if ($memory.dualChannelHint -eq $true) { $channelText = [string]$script:T.labels.dualChannel }
    $memNote = ''
    if ($memTotal -gt 0) {
        $memNote = ($script:T.score.notes.memory -f [string]([Math]::Round($memTotal / 1073741824.0, 1)), $memType, [string]$memory.usedPct, $channelText)
    }
    $scoreParts += [ordered]@{ key = 'memory'; label = [string]$script:T.labels.memory; score = $memScore; weight = 0.2; note = $memNote }

    # Storage
    $storageScore = 50
    $storageNote = [string]$script:T.labels.unknownDisk
    if ($disks.Count -gt 0) {
        $bestDisk = $disks[0]
        foreach ($dsk in $disks) {
            $mt = [string]$dsk.mediaType
            if ($mt -eq 'NVMe') { $bestDisk = $dsk; break }
            if ($mt -eq 'SSD' -and [string]$bestDisk.mediaType -ne 'NVMe') { $bestDisk = $dsk }
        }
        $media = [string]$bestDisk.mediaType
        $iface = [string]$bestDisk.interfaceType
        $diskTypeScore = 65
        $diskTypeText = [string]$script:T.fmt.noData
        if ($media -eq 'SSD' -and $iface -eq 'NVMe') { $diskTypeScore = 100; $diskTypeText = 'NVMe' }
        elseif ($media -eq 'SSD') { $diskTypeScore = 88; $diskTypeText = 'SSD' }
        elseif ($media -eq 'HDD') { $diskTypeScore = 55; $diskTypeText = 'HDD' }
        elseif ($media -eq 'SCM') { $diskTypeScore = 95; $diskTypeText = 'SCM' }
        $healthScore = 70
        $healthText = [string]$script:T.status.unknown
        switch ([string]$bestDisk.health) {
            'healthy' { $healthScore = 100; $healthText = [string]$script:T.status.healthy }
            'warning' { $healthScore = 60; $healthText = [string]$script:T.status.warning }
            'critical' { $healthScore = 20; $healthText = [string]$script:T.status.critical }
            default { $healthScore = 70; $healthText = [string]$script:T.status.unknown }
        }
        $freeRatio = 0
        $freeText = '0'
        $sysVolForScore = $null
        foreach ($ld in $logicalDisksRaw) {
            if ($null -ne $ld -and [string]$ld.DeviceID -eq [string]$env:SystemDrive) { $sysVolForScore = $ld; break }
        }
        if ($null -ne $sysVolForScore) {
            $svTotal = To-Num $sysVolForScore.Size
            $svFree = To-Num $sysVolForScore.FreeSpace
            if ($null -ne $svTotal -and $svTotal -gt 0 -and $null -ne $svFree) {
                $freeRatio = [double]($svFree / $svTotal)
                $freeText = [string][Math]::Round($freeRatio * 100, 0)
            }
        }
        $freeScore = 100
        if ($freeRatio -lt 0.08) { $freeScore = 30 }
        elseif ($freeRatio -lt 0.15) { $freeScore = 60 }
        elseif ($freeRatio -lt 0.3) { $freeScore = 85 }
        $storageScore = Clamp-Score ([int][Math]::Round(($diskTypeScore * 0.5) + ($healthScore * 0.3) + ($freeScore * 0.2)))
        $storageNote = ($script:T.score.notes.storage -f $diskTypeText, $healthText, $freeText)
    }
    $scoreParts += [ordered]@{ key = 'storage'; label = [string]$script:T.labels.storage; score = $storageScore; weight = 0.25; note = $storageNote }

    # GPU
    $gpuScore = 60
    $gpuNote = [string]$script:T.fmt.noData
    if ($gpus.Count -gt 0) {
        $gpuScore = 55
        foreach ($g in $gpus) {
            $nm = [string]$g.name
            $tier = 60
            if ($nm -match '(?i)(rtx\s*5\d{3}|rtx\s*4\d{3}|rx\s*9\d{3}|rx\s*7\d{3}|arc\s*[ab]\d{3})') { $tier = 95 }
            elseif ($nm -match '(?i)(rtx\s*3\d{3}|rx\s*6\d{3})') { $tier = 86 }
            elseif ($nm -match '(?i)(gtx\s*16\d{2}|rx\s*5\d{3})') { $tier = 76 }
            elseif ($nm -match '(?i)(gtx\s*10\d{2})') { $tier = 66 }
            elseif ($nm -match '(?i)(iris\s*xe|iris\s*plus)') { $tier = 55 }
            elseif ($nm -match '(?i)(intel.*(uhd|hd\s*graphics)|radeon.*(vega|graphics))') { $tier = 45 }
            if ($g.discrete -ne $true -and $tier -eq 60) { $tier = 50 }
            if ($tier -gt $gpuScore) { $gpuScore = $tier }
        }
        $firstGpu = $gpus[0]
        $gpuTypeText = [string]$script:T.labels.integrated
        if ($firstGpu.discrete -eq $true) { $gpuTypeText = [string]$script:T.labels.discrete }
        $gpuNote = ($script:T.score.notes.gpu -f [string]$firstGpu.name, $gpuTypeText)
    }
    $scoreParts += [ordered]@{ key = 'gpu'; label = [string]$script:T.labels.gpu; score = $gpuScore; weight = 0.15; note = $gpuNote }

    # System state
    $sysScore = 70
    $actText = [string]$script:T.status.unknown
    if ($system.activation -eq [string]$script:T.status.activated) { $sysScore += 12; $actText = [string]$script:T.status.activated }
    elseif ($system.activation -eq [string]$script:T.status.grace) { $sysScore += 6; $actText = [string]$script:T.status.grace }
    elseif ($system.activation -eq [string]$script:T.status.notActivated) { $sysScore -= 15; $actText = [string]$script:T.status.notActivated }
    if ($script:SecureBoot -eq $true) { $sysScore += 6 }
    if ($null -ne $sysVolumeFree -and $sysVolumeFree -ge 64GB) { $sysScore += 6 }
    if ($system.uptimeSec -gt 0) {
        $uptimeDays = [double]$system.uptimeSec / 86400.0
        if ($uptimeDays -le 30) { $sysScore += 3 } else { $sysScore -= 6 }
    }
    if ($null -ne $osBuildNum -and $osBuildNum -ge 22621) { $sysScore += 3 }
    if ($system.powerPlan -eq [string]$script:T.labels.planPowerSaver) { $sysScore -= 6 }
    elseif ($system.powerPlan -eq [string]$script:T.labels.planHighPerformance -or $system.powerPlan -eq [string]$script:T.labels.planUltimate) { $sysScore += 2 }
    $scoreBuildNum = To-IntOrNull $system.build
    if ($null -ne $scoreBuildNum -and $scoreBuildNum -lt 19045) { $sysScore -= 5 }
    $sysScore = Clamp-Score $sysScore
    $secBootText = [string]$script:T.status.unknown
    if ($script:SecureBoot -eq $true) { $secBootText = [string]$script:T.status.on }
    elseif ($script:SecureBoot -eq $false) { $secBootText = [string]$script:T.status.off }
    $sysNote = ($script:T.score.notes.system -f $actText, $secBootText, (Format-Gb $sysVolumeFree), [string][Math]::Round($system.uptimeSec / 3600.0, 0))
    $scoreParts += [ordered]@{ key = 'system'; label = [string]$script:T.labels.system; score = $sysScore; weight = 0.15; note = $sysNote }
} catch {
    Add-SectionFailure 'score' $_.Exception.Message
}
Stop-Timer 'score' $swSec

$totalScore = 0
foreach ($sp in $scoreParts) { $totalScore += ($sp.score * $sp.weight) }
$totalScore = [int][Math]::Round($totalScore)
$scoreLevel = 'poor'
if ($totalScore -ge 90) { $scoreLevel = 'excellent' }
elseif ($totalScore -ge 80) { $scoreLevel = 'good' }
elseif ($totalScore -ge 60) { $scoreLevel = 'fair' }
$score = [ordered]@{ total = $totalScore; level = $scoreLevel; parts = $scoreParts }

# ---------- 20. meta ----------
if ($script:SkippedProbes.Count -gt 0) {
    Add-Warn ($script:T.warnings.probeSkipped -f ($script:SkippedProbes -join ', '))
}
$elevationGains = @()
if (-not $script:IsAdmin) {
    foreach ($g in @($script:T.elevationGains)) { if ($null -ne $g) { $elevationGains += [string]$g } }
}
$meta = [ordered]@{
    scanMs           = [int]$script:TotalSw.ElapsedMilliseconds
    generatedAt      = (Get-Date).ToString('yyyy-MM-ddTHH:mm:sszzz')
    isAdmin          = $script:IsAdmin
    elevationGains   = $elevationGains
    warnings         = @($script:Warnings)
    collectorVersion = $script:CollectorVersion
}

# ---------- 21. Emit JSON (UTF-8, no BOM) ----------
$result = [ordered]@{
    meta        = $meta
    system      = $system
    motherboard = $motherboard
    cpu         = $cpu
    memory      = $memory
    gpus        = @($gpus)
    displays    = @($displays)
    disks       = @($disks)
    network     = $network
    runtime     = $runtime
    security    = $security
    compat      = $compat
    score       = $score
}

try {
    $json = ConvertTo-Json -InputObject $result -Depth 14
    $dir = [System.IO.Path]::GetDirectoryName($OutFile)
    if (-not [string]::IsNullOrWhiteSpace($dir) -and -not (Test-Path -LiteralPath $dir)) {
        [void][System.IO.Directory]::CreateDirectory($dir)
    }
    [System.IO.File]::WriteAllText($OutFile, $json, (New-Object System.Text.UTF8Encoding($false)))
} catch {
    [Console]::Error.WriteLine('failed to write scan result: ' + [string]$_.Exception.Message)
    exit 1
}
exit 0
