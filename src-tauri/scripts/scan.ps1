function Get-TpmFacts {
    $r = [ordered]@{ version = $null; enabled = $null; method = $null }
    # Admin: Win32_Tpm gives the spec version directly (standard users get access denied).
    if ($script:IsAdmin) {
        $tpm = Get-CimOne -Class 'Win32_Tpm' -Namespace 'root/cimv2/security/microsofttpm' -TimeoutSec 4
        if ($null -ne $tpm) {
            $spec = [string]$tpm.SpecVersion
            if ($spec -match '2\.0') { $r.version = '2.0' }
            elseif ($spec -match '1\.2') { $r.version = '1.2' }
            $enabled = $false
            if ($tpm.IsEnabled_InitialValue) { $enabled = $true }
            $r.enabled = $enabled
            $r.method = 'cim'
            return $r
        }
    }
    # Standard user: infer from ACPI device enumeration.
    #   ACPI\MSFT0101 = TPM 2.0 device exposed by Windows;
    #   ACPI\IFX0102 / BCM0102 / NTC0102 / STM0102 / ATML0102 / WEC0001 = TPM 1.2 families.
    # Probe result: Get-Tpm / Win32_Tpm are NOT readable without elevation, but the ACPI
    # device node is readable by standard users, so this is the fallback used here.
    $acpiRoot = 'HKLM:\SYSTEM\CurrentControlSet\Enum\ACPI'
    $found = $null
    foreach ($id in @('MSFT0101', 'IFX0102', 'BCM0102', 'NTC0102', 'STM0102', 'WEC0001', 'ATML0102', 'PNP0C31', 'INTC0102')) {
        if (Test-Path -LiteralPath (Join-Path $acpiRoot $id)) { $found = $id; break }
    }
    if ($null -ne $found) {
        if ($found -eq 'MSFT0101') { $r.version = '2.0' }
        elseif ($found -eq 'PNP0C31' -or $found -eq 'INTC0102') { $r.version = $null }
        else { $r.version = '1.2' }
        $r.enabled = $true
        $r.method = 'acpi'
        return $r
    }
    if (Test-Path -LiteralPath 'HKLM:\SYSTEM\CurrentControlSet\Services\TPM') {
        $r.enabled = $false
        $r.method = 'service'
    }
    return $r
}

function Get-PowerPlanName {
    try {
        $out = (& powercfg.exe /getactivescheme 2>$null | Out-String)
    } catch {
        return $null
    }
    if ([string]::IsNullOrWhiteSpace($out)) { return $null }
    $guid = $null
    if ($out -match '([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})') {
        $guid = $matches[1].ToLower()
    }
    if ($guid -eq '381b4222-f694-41f0-9685-ff5bb260df2e') { return [string]$script:T.labels.planBalanced }
    if ($guid -eq '8c5e7fda-e8bf-4a96-9a85-a6e23a8c635c') { return [string]$script:T.labels.planHighPerformance }
    if ($guid -eq 'a1841308-3541-4fab-bc81-f71556f20b4a') { return [string]$script:T.labels.planPowerSaver }
    if ($guid -eq 'e9a42b02-d5df-448d-aa00-03f14749eb61') { return [string]$script:T.labels.planUltimate }
    # Custom / OEM power plans: use the display name from powercfg output when it is sane.
    $name = $null
    if ($out -match '\(([^()]+)\)\s*$') { $name = $matches[1].Trim() }
    if (-not [string]::IsNullOrWhiteSpace($name)) {
        $bad = [string][char]0xFFFD
        if (-not $name.Contains($bad)) { return $name }
    }
    return [string]$script:T.labels.customPowerPlan
}

