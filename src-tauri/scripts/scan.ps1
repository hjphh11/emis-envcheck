function Get-CimSafe {
    param(
        [string]$Class,
        [string]$Namespace = 'root/cimv2',
        [string]$Filter = '',
        [int]$TimeoutSec = 8
    )
    try {
        $params = @{
            ClassName           = $Class
            Namespace           = $Namespace
            ErrorAction         = 'Stop'
            OperationTimeoutSec = $TimeoutSec
        }
        if ($Filter -and $Filter.Trim().Length -gt 0) { $params['Filter'] = $Filter }
        $items = @(Get-CimInstance @params)
        if ($items.Count -eq 0) { return $null }
        return $items
    } catch {
        return $null
    }
}

function Get-CimOne {
    param(
        [string]$Class,
        [string]$Namespace = 'root/cimv2',
        [string]$Filter = '',
        [int]$TimeoutSec = 8
    )
    $items = @(Get-CimSafe -Class $Class -Namespace $Namespace -Filter $Filter -TimeoutSec $TimeoutSec)
    if ($items.Count -eq 0) { return $null }
    return $items[0]
}

function Decode-U16 {
    param($Values)
    if ($null -eq $Values) { return $null }
    $sb = New-Object System.Text.StringBuilder
    foreach ($v in $Values) {
        $n = To-IntOrNull $v
        if ($null -eq $n) { continue }
        if ($n -le 0) { break }
        [void]$sb.Append([char]$n)
    }
    $s = $sb.ToString().Trim()
    if ($s.Length -eq 0) { return $null }
    return $s
}

