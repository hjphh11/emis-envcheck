# ---------- 9. cpu ----------
$cpu = [ordered]@{
    brand = [string]$script:T.labels.unknownCpu; vendor = $null; physicalCores = $null; logicalCores = $null
    baseMhz = $null; maxMhz = $null; currentMhz = $null; l2Bytes = $null; l3Bytes = $null
    socket = $null; virtualization = $null; instructions = @(); arch = $null; usagePct = $null
}
$swSec = Start-Timer
try {
    if ($cpuList.Count -gt 0) {
        $cores = 0; $threads = 0; $maxClock = 0; $l2 = 0; $l3 = 0; $loads = @()
        $first = $null
        foreach ($p in $cpuList) {
            if ($null -eq $p) { continue }
            if ($null -eq $first) { $first = $p }
            $c = To-IntOrNull $p.NumberOfCores
            if ($null -ne $c) { $cores += $c }
            $threadCount = To-IntOrNull $p.NumberOfLogicalProcessors
            if ($null -ne $threadCount) { $threads += $threadCount }
            $mc = To-IntOrNull $p.MaxClockSpeed
            if ($null -ne $mc -and $mc -gt $maxClock) { $maxClock = $mc }
            $c2 = To-IntOrNull $p.L2CacheSize
            if ($null -ne $c2) { $l2 += $c2 }
            $c3 = To-IntOrNull $p.L3CacheSize
            if ($null -ne $c3) { $l3 += $c3 }
            $ld = To-IntOrNull $p.LoadPercentage
            if ($null -ne $ld) { $loads += $ld }
        }
        if ($null -ne $first) {
            $brandName = Clean-Text $first.Name
            if ($null -ne $brandName) { $cpu.brand = $brandName }
            $mfr = [string]$first.Manufacturer
            if ($mfr -match '(?i)intel') { $cpu.vendor = 'Intel' }
            elseif ($mfr -match '(?i)amd') { $cpu.vendor = 'AMD' }
            elseif ($mfr) { $cpu.vendor = Clean-Text $mfr }
            if ($cores -gt 0) { $cpu.physicalCores = $cores }
            if ($threads -gt 0) { $cpu.logicalCores = $threads }
            if ($maxClock -gt 0) { $cpu.baseMhz = $maxClock }
            if ($l2 -gt 0) { $cpu.l2Bytes = [long]$l2 * 1024 }
            if ($l3 -gt 0) { $cpu.l3Bytes = [long]$l3 * 1024 }
            $cpu.socket = Clean-Text $first.SocketDesignation
            $addrWidth = To-IntOrNull $first.AddressWidth
            if ($null -ne $addrWidth) {
                if ($addrWidth -ge 64) { $cpu.arch = 'x64' } else { $cpu.arch = 'x86' }
            }
            $virtFw = $null
            if ($null -ne $first.VirtualizationFirmwareEnabled) { $virtFw = [bool]$first.VirtualizationFirmwareEnabled }
            if ($null -ne $csInfo -and $csInfo.HypervisorPresent -eq $true) { $cpu.virtualization = $true }
            else { $cpu.virtualization = $virtFw }
            if ($loads.Count -gt 0) {
                $sum = 0
                foreach ($l in $loads) { $sum += $l }
                $cpu.usagePct = [int][Math]::Round($sum / $loads.Count)
            }
        }
    } else {
        # Registry fallback when WMI is unavailable.
        $regCpu = Get-RegItem 'HKLM:\HARDWARE\DESCRIPTION\System\CentralProcessor\0'
        if ($null -ne $regCpu) {
            $name = Clean-Text $regCpu.ProcessorNameString
            if ($null -ne $name) { $cpu.brand = $name }
            $mhz = To-IntOrNull $regCpu.'~MHz'
            if ($null -ne $mhz) { $cpu.baseMhz = $mhz; $cpu.currentMhz = $mhz }
            if ([string]$regCpu.Identifier -match '(?i)intel') { $cpu.vendor = 'Intel' }
            else { $cpu.vendor = 'AMD' }
        }
        Add-Warn ([string]$script:T.warnings.cpuFallback)
    }
    $regCpu0 = Get-RegItem 'HKLM:\HARDWARE\DESCRIPTION\System\CentralProcessor\0'
    if ($null -ne $regCpu0) {
        $cur = To-IntOrNull $regCpu0.'~MHz'
        if ($null -ne $cur -and $cur -gt 0) { $cpu.currentMhz = $cur }
    }
    # Instruction set via kernel32.IsProcessorFeaturePresent (readable by standard users).
    $featOk = Initialize-CpuFeatures
    $script:CpuFeaturesOk = $featOk
    $instr = @()
    if ($featOk) {
        if (Test-CpuFeature 6)  { $instr += 'SSE' }
        if (Test-CpuFeature 10) { $instr += 'SSE2' }
        if (Test-CpuFeature 13) { $instr += 'SSE3' }
        if (Test-CpuFeature 36) { $instr += 'SSSE3' }
        if (Test-CpuFeature 37) { $instr += 'SSE4.1' }
        if (Test-CpuFeature 38) { $instr += 'SSE4.2' }
        if (Test-CpuFeature 39) { $instr += 'AVX' }
        if (Test-CpuFeature 40) { $instr += 'AVX2' }
        if (Test-CpuFeature 41) { $instr += 'AVX512F' }
        # POPCNT shares the CPUID feature bit family with SSE4.2; every SSE4.2 CPU has it.
        if ($instr -contains 'SSE4.2') { $instr += 'POPCNT' }
    }
    $cpu.instructions = $instr
} catch {
    Add-SectionFailure 'cpu' $_.Exception.Message
}
Stop-Timer 'cpu' $swSec

# ---------- 10. memory ----------
$memory = [ordered]@{
    totalBytes = 0; availableBytes = 0; usedBytes = 0; usedPct = 0
    modules = @(); dualChannelHint = $null
}
$swSec = Start-Timer
try {
    $total = $null
    if ($null -ne $csInfo) { $total = To-LongOrNull $csInfo.TotalPhysicalMemory }
    if (($null -eq $total -or $total -le 0) -and $null -ne $osInfo) {
        $tv = To-LongOrNull $osInfo.TotalVisibleMemorySize
        if ($null -ne $tv) { $total = $tv * 1024 }
    }
    $avail = $null
    if ($null -ne $osInfo) {
        $fp = To-LongOrNull $osInfo.FreePhysicalMemory
        if ($null -ne $fp) { $avail = $fp * 1024 }
    }
    if ($null -ne $total -and $total -gt 0) {
        $memory.totalBytes = [long]$total
        if ($null -ne $avail -and $avail -ge 0) {
            if ($avail -gt $total) { $avail = $total }
            $memory.availableBytes = [long]$avail
        }
        $used = $memory.totalBytes - $memory.availableBytes
        if ($used -lt 0) { $used = 0 }
        $memory.usedBytes = [long]$used
        $memory.usedPct = [double][Math]::Round(($used * 100.0) / $memory.totalBytes, 1)
    }
    $modules = @()
    foreach ($m in $memModulesRaw) {
        if ($null -eq $m) { continue }
        $typeName = $null
        $tcode = To-IntOrNull $m.SMBIOSMemoryType
        if ($null -ne $tcode) {
            $map = @{ 20 = 'DDR'; 21 = 'DDR2'; 22 = 'DDR2 FB-DIMM'; 24 = 'DDR3'; 26 = 'DDR4'; 27 = 'LPDDR'; 28 = 'LPDDR2'; 29 = 'LPDDR3'; 30 = 'LPDDR4'; 34 = 'DDR5'; 35 = 'LPDDR5' }
            if ($map.ContainsKey($tcode)) { $typeName = $map[$tcode] }
        }
        $formName = $null
        $fcode = To-IntOrNull $m.FormFactor
        if ($null -ne $fcode) {
            $fmap = @{ 8 = 'DIMM'; 12 = 'SODIMM'; 13 = 'SRIMM'; 16 = 'FB-DIMM' }
            if ($fmap.ContainsKey($fcode)) { $formName = $fmap[$fcode] }
        }
        $modules += [ordered]@{
            slot          = Clean-Text $m.DeviceLocator
            manufacturer  = Clean-Text $m.Manufacturer
            partNumber    = Clean-Text $m.PartNumber
            serial        = Clean-Text $m.SerialNumber
            capacityBytes = To-LongOrNull $m.Capacity
            ratedMhz      = To-IntOrNull $m.Speed
            speedMhz      = To-IntOrNull $m.ConfiguredClockSpeed
            type          = $typeName
            formFactor    = $formName
            voltageMv     = To-IntOrNull $m.ConfiguredVoltage
        }
    }
    $memory.modules = $modules
    if ($modules.Count -ge 2) {
        $firstCap = $modules[0].capacityBytes
        $symmetric = $true
        foreach ($mo in $modules) {
            if ($null -ne $firstCap -and $mo.capacityBytes -ne $firstCap) { $symmetric = $false }
        }
        $memory.dualChannelHint = $symmetric
    } elseif ($modules.Count -eq 1) {
        $memory.dualChannelHint = $false
    }
    if ($memory.totalBytes -eq 0) {
        Add-SectionFailure 'memory' 'TotalPhysicalMemory unavailable'
    }
} catch {
    Add-SectionFailure 'memory' $_.Exception.Message
}
Stop-Timer 'memory' $swSec

# ---------- 11. gpus ----------
$gpus = @()
$swSec = Start-Timer
try {
    # VRAM: prefer the display class registry HardwareInformation.qwMemorySize.
    # Win32_VideoController.AdapterRAM is UInt32 and saturates/overflows above 4GB.
    # Read via the .NET registry API: the PowerShell provider can deny enumeration of this
    # key for standard users even though opening the individual subkeys is allowed.
    $vramMap = @{}
    try {
        $classKey = [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey('SYSTEM\CurrentControlSet\Control\Class\{4d36e968-e325-11ce-bfc1-08002be10318}')
        if ($null -ne $classKey) {
            foreach ($subName in $classKey.GetSubKeyNames()) {
                if ($subName -notmatch '^\d{4}$') { continue }
                $subKey = $classKey.OpenSubKey($subName)
                if ($null -eq $subKey) { continue }
                $desc = Clean-Text $subKey.GetValue('DriverDesc')
                $qw = $subKey.GetValue('HardwareInformation.qwMemorySize')
                if ($null -ne $desc) { $vramMap[$desc] = To-LongOrNull $qw }
                $subKey.Close()
            }
            $classKey.Close()
        }
    } catch { }
    foreach ($vc in $videoList) {
        if ($null -eq $vc) { continue }
        $name = Clean-Text $vc.Name
        if ($null -eq $name) { continue }
        $vram = $null
        if ($vramMap.ContainsKey($name)) { $vram = $vramMap[$name] }
        if ($null -eq $vram -or $vram -le 0) {
            $adapterRam = To-LongOrNull $vc.AdapterRAM
            if ($null -ne $adapterRam -and $adapterRam -gt 0 -and $adapterRam -lt 4000000000) { $vram = $adapterRam } else { $vram = $null }
        }
        $vendor = $null
        $pnp = [string]$vc.PNPDeviceID
        if ($pnp -match '(?i)VEN_10DE') { $vendor = 'NVIDIA' }
        elseif ($pnp -match '(?i)VEN_1002|VEN_1022') { $vendor = 'AMD' }
        elseif ($pnp -match '(?i)VEN_8086') { $vendor = 'Intel' }
        elseif ($pnp -match '(?i)VEN_1A03') { $vendor = 'ASPEED' }
        $discrete = $null
        if ($name -match '(?i)(geforce|rtx|gtx|radeon\s*rx|radeon\s*pro|quadro|arc\s*[ab])') { $discrete = $true }
        elseif ($name -match '(?i)(intel.*(uhd|hd|iris)|radeon.*(vega|graphics)|microsoft basic|remote display)') { $discrete = $false }
        $drvDate = Cim-Date $vc.DriverDate
        $gpus += [ordered]@{
            name          = $name
            vendor        = $vendor
            vramBytes     = $vram
            driverVersion = Clean-Text $vc.DriverVersion
            driverDate    = $(if ($null -ne $drvDate) { Iso-Date $drvDate } else { $null })
            discrete      = $discrete
            status        = Clean-Text $vc.Status
        }
    }
    if ($gpus.Count -eq 0) { Add-Warn ([string]$script:T.warnings.noGpu) }
} catch {
    Add-SectionFailure 'gpu' $_.Exception.Message
}
Stop-Timer 'gpu' $swSec

# ---------- 12. displays ----------
$displays = @()
$swSec = Start-Timer
try {
    $monIds = @(Get-CimSafe -Class 'WmiMonitorID' -Namespace 'root/wmi' -TimeoutSec 5)
    $monBasic = @(Get-CimSafe -Class 'WmiMonitorBasicDisplayParams' -Namespace 'root/wmi' -TimeoutSec 5)
    $basicMap = @{}
    foreach ($basicMon in $monBasic) {
        if ($null -eq $basicMon) { continue }
        $basicMap[[string]$basicMon.InstanceName] = $basicMon
    }
    $displayDevices = @(Get-DisplayDevices)
    if ($displayDevices.Count -eq 1 -and $null -eq $displayDevices[0]) { $displayDevices = @() }
    foreach ($dd in $displayDevices) {
        if ($null -eq $dd) { continue }
        $edidCode = $null
        $monIdText = [string]$dd.monitorId
        if ($monIdText -match '(?i)DISPLAY#([0-9A-Z]{3}[0-9A-F]{4})#') { $edidCode = $matches[1].ToUpper() }
        $matchedMon = $null
        if ($null -ne $edidCode) {
            foreach ($mon in $monIds) {
                if ($null -eq $mon) { continue }
                if ([string]$mon.InstanceName -match [regex]::Escape($edidCode)) { $matchedMon = $mon; break }
            }
        }
        $mfr = $null
        $friendly = $null
        $sizeInch = $null
        if ($null -ne $matchedMon) {
            $mfr = Decode-U16 $matchedMon.ManufacturerName
            $friendly = Decode-U16 $matchedMon.UserFriendlyName
            $monInstance = [string]$matchedMon.InstanceName
            if ($basicMap.ContainsKey($monInstance)) {
                $basicInfo = $basicMap[$monInstance]
                $hcm = To-Num $basicInfo.MaxHorizontalImageSize
                $vcm = To-Num $basicInfo.MaxVerticalImageSize
                if ($null -ne $hcm -and $null -ne $vcm -and $hcm -gt 0 -and $vcm -gt 0) {
                    # EDID image size is in centimetres; the diagonal is presented in inches.
                    $diag = [Math]::Sqrt(($hcm * $hcm) + ($vcm * $vcm)) / 2.54
                    $sizeInch = [double][Math]::Round($diag, 1)
                }
            }
        }
        if ($null -eq $mfr -and $null -ne $edidCode) { $mfr = $edidCode.Substring(0, 3) }
        $dispName = $friendly
        if ($null -eq $dispName) {
            $monName = Clean-Text $dd.monitorName
            if ($null -ne $monName -and $monName -notmatch '(?i)generic') { $dispName = $monName }
        }
        if ($null -eq $dispName) {
            if ($null -ne $mfr) { $dispName = ($mfr + ' ' + [string]$script:T.labels.monitor) }
            else { $dispName = [string]$script:T.labels.monitor }
        }
        $res = $null
        $resW = To-IntOrNull $dd.width
        $resH = To-IntOrNull $dd.height
        if ($null -ne $resW -and $null -ne $resH -and $resW -gt 0 -and $resH -gt 0) { $res = ('{0}x{1}' -f $resW, $resH) }
        $hz = To-IntOrNull $dd.refreshHz
        if ($null -ne $hz -and $hz -le 0) { $hz = $null }
        $displays += [ordered]@{
            name         = $dispName
            manufacturer = $mfr
            resolution   = $res
            refreshHz    = $hz
            sizeInch     = $sizeInch
            primary      = [bool]$dd.primary
        }
    }
    # Fallback when the user32 enumeration is unavailable: WmiMonitorID only.
    if ($displays.Count -eq 0) {
        $desktopMon = @(Get-CimSafe -Class 'Win32_DesktopMonitor' -TimeoutSec 5)
        $primaryPnp = $null
        if ($desktopMon.Count -gt 0 -and $null -ne $desktopMon[0]) { $primaryPnp = [string]$desktopMon[0].PNPDeviceID }
        $idx = 0
        foreach ($mon in $monIds) {
            if ($null -eq $mon) { continue }
            $inst = [string]$mon.InstanceName
            $mfr = Decode-U16 $mon.ManufacturerName
            $friendly = Decode-U16 $mon.UserFriendlyName
            $sizeInch = $null
            if ($basicMap.ContainsKey($inst)) {
                $basicInfo = $basicMap[$inst]
                $hcm = To-Num $basicInfo.MaxHorizontalImageSize
                $vcm = To-Num $basicInfo.MaxVerticalImageSize
                if ($null -ne $hcm -and $null -ne $vcm -and $hcm -gt 0 -and $vcm -gt 0) {
                    $diag = [Math]::Sqrt(($hcm * $hcm) + ($vcm * $vcm)) / 2.54
                    $sizeInch = [double][Math]::Round($diag, 1)
                }
            }
            $isPrimary = $false
            if ($null -ne $primaryPnp -and $primaryPnp.Length -gt 0) {
                if ($inst -and $inst.StartsWith($primaryPnp, [StringComparison]::OrdinalIgnoreCase)) { $isPrimary = $true }
            } elseif ($idx -eq 0) {
                $isPrimary = $true
            }
            $res = $null
            $hz = $null
            if ($isPrimary) {
                $res = $system.resolution
                $hz = $system.refreshHz
            }
            $dispName = $friendly
            if ($null -eq $dispName) {
                if ($null -ne $mfr) { $dispName = ($mfr + ' ' + [string]$script:T.labels.monitor) }
                else { $dispName = [string]$script:T.labels.monitor }
            }
            $displays += [ordered]@{
                name         = $dispName
                manufacturer = $mfr
                resolution   = $res
                refreshHz    = $hz
                sizeInch     = $sizeInch
                primary      = $isPrimary
            }
            $idx++
        }
    }
    # Fill the primary resolution / refresh on the system record when it is still empty.
    if ($null -eq $system.resolution) {
        foreach ($dp in $displays) {
            if ($dp.primary -eq $true -and $null -ne $dp.resolution) { $system.resolution = $dp.resolution; break }
        }
    }
    if ($null -eq $system.refreshHz) {
        foreach ($dp in $displays) {
            if ($dp.primary -eq $true -and $null -ne $dp.refreshHz) { $system.refreshHz = $dp.refreshHz; break }
        }
    }
    if ($displays.Count -eq 0) { Add-Warn ([string]$script:T.warnings.displayMissing) }
} catch {
    Add-SectionFailure 'display' $_.Exception.Message
}
Stop-Timer 'display' $swSec

# ---------- 13. disks ----------
$disks = @()
$swSec = Start-Timer
try {
    $physDisks = @(Get-CimSafe -Class 'MSFT_PhysicalDisk' -Namespace 'root/Microsoft/Windows/Storage' -TimeoutSec 5)
    $msftDisks = @(Get-CimSafe -Class 'MSFT_Disk' -Namespace 'root/Microsoft/Windows/Storage' -TimeoutSec 5)
    $msftParts = @(Get-CimSafe -Class 'MSFT_Partition' -Namespace 'root/Microsoft/Windows/Storage' -TimeoutSec 5)
    $reliability = @(Get-CimSafe -Class 'MSFT_StorageReliabilityCounter' -Namespace 'root/Microsoft/Windows/Storage' -TimeoutSec 4)
    $relMap = @{}
    foreach ($rl in $reliability) {
        if ($null -eq $rl) { continue }
        $devId = To-IntOrNull $rl.DeviceId
        if ($null -ne $devId) { $relMap[$devId] = $rl }
    }
    $mediaMap = @{ 3 = 'HDD'; 4 = 'SSD'; 5 = 'SCM' }
    $busMap = @{ 7 = 'USB'; 8 = 'RAID'; 10 = 'SAS'; 11 = 'SATA'; 17 = 'NVMe' }
    $partByDisk = @{}
    foreach ($part in $msftParts) {
        if ($null -eq $part) { continue }
        $dn = To-IntOrNull $part.DiskNumber
        if ($null -eq $dn) { continue }
        if (-not $partByDisk.ContainsKey($dn)) { $partByDisk[$dn] = @() }
        $partByDisk[$dn] += $part
    }
    foreach ($dd in $diskDrivesRaw) {
        if ($null -eq $dd) { continue }
        $model = Clean-Text $dd.Model
        if ($null -eq $model) { $model = [string]$script:T.labels.unknownDisk }
        $diskIndex = To-IntOrNull $dd.Index
        $pnp = [string]$dd.PNPDeviceID
        $interface = Clean-Text $dd.InterfaceType
        if ($interface -eq 'SCSI' -and $pnp -match '(?i)nvme') { $interface = 'NVMe' }
        $media = $null
        $health = 'unknown'
        $healthPct = $null
        $tempC = $null
        $powerHours = $null
        $powerCycles = $null
        $phys = $null
        foreach ($pp in $physDisks) {
            if ($null -eq $pp) { continue }
            $physId = To-IntOrNull $pp.DeviceId
            if ($null -ne $diskIndex -and $null -ne $physId -and $physId -eq $diskIndex) { $phys = $pp; break }
        }
        if ($null -ne $phys) {
            $mt = To-IntOrNull $phys.MediaType
            if ($null -ne $mt -and $mediaMap.ContainsKey($mt)) { $media = $mediaMap[$mt] }
            $bt = To-IntOrNull $phys.BusType
            if ($null -ne $bt -and $busMap.ContainsKey($bt)) { $interface = $busMap[$bt] }
            $hs = To-IntOrNull $phys.HealthStatus
            if ($hs -eq 0) { $health = 'healthy' }
            elseif ($hs -eq 1) { $health = 'warning' }
            elseif ($hs -eq 2) { $health = 'critical' }
        }
        if ($null -ne $diskIndex -and $relMap.ContainsKey($diskIndex)) {
            $rl = $relMap[$diskIndex]
            $wear = To-IntOrNull $rl.Wear
            if ($null -ne $wear -and $wear -ge 0 -and $wear -le 100) { $healthPct = 100 - $wear }
            $tempVal = To-Num $rl.Temperature
            if ($null -ne $tempVal -and $tempVal -gt 0 -and $tempVal -lt 100) { $tempC = [int][Math]::Round($tempVal) }
            $ph = To-LongOrNull $rl.PowerOnHours
            if ($null -ne $ph -and $ph -gt 0) { $powerHours = $ph }
            $pc = To-LongOrNull $rl.PowerCycleCount
            if ($null -ne $pc -and $pc -ge 0) { $powerCycles = $pc }
        }
        $volumes = @()
        if ($null -ne $diskIndex -and $partByDisk.ContainsKey($diskIndex)) {
            foreach ($part in $partByDisk[$diskIndex]) {
                $letter = [string]$part.DriveLetter
                if ([string]::IsNullOrWhiteSpace($letter)) { continue }
                if ($letter.Length -eq 1) { $letter = $letter + ':' }
                $ld = $null
                foreach ($cand in $logicalDisksRaw) {
                    if ($null -ne $cand -and [string]$cand.DeviceID -eq $letter) { $ld = $cand; break }
                }
                if ($null -eq $ld) { continue }
                $volumes += [ordered]@{
                    drive      = $letter
                    label      = Clean-Text $ld.VolumeName
                    fs         = Clean-Text $ld.FileSystem
                    totalBytes = [long](To-LongOrNull $ld.Size)
                    freeBytes  = [long](To-LongOrNull $ld.FreeSpace)
                }
            }
        }
        $disks += [ordered]@{
            model         = $model
            vendor        = $null
            serial        = Clean-Text $dd.SerialNumber
            firmware      = Clean-Text $dd.FirmwareRevision
            interfaceType = $interface
            mediaType     = $media
            totalBytes    = To-LongOrNull $dd.Size
            health        = $health
            healthPct     = $healthPct
            temperatureC  = $tempC
            powerOnHours  = $powerHours
            powerCycles   = $powerCycles
            volumes       = $volumes
        }
    }
    if ($relMap.Count -eq 0 -and $disks.Count -gt 0) {
        Add-Warn ([string]$script:T.warnings.noReliability)
    }
} catch {
    Add-SectionFailure 'disk' $_.Exception.Message
}
Stop-Timer 'disk' $swSec

# ---------- 14. network ----------
$network = [ordered]@{ adapters = @(); internet = $null; latencyMs = $null; dnsOk = $null }
$swSec = Start-Timer
try {
    $cfgByIndex = @{}
    foreach ($cfg in $netConfigsRaw) {
        if ($null -eq $cfg) { continue }
        $idx = To-IntOrNull $cfg.Index
        if ($null -ne $idx) { $cfgByIndex[$idx] = $cfg }
    }
    # Wi-Fi: netsh output is parsed locale-agnostically. "SSID" is not translated and the
    # signal line is matched with a generic "NN%" pattern instead of a localized key.
    $wifiSsid = $null
    $wifiSignal = $null
    try {
        $netshOut = (& netsh.exe wlan show interfaces 2>$null | Out-String)
        if ($netshOut) {
            if ($netshOut -match '(?im)^\s*SSID\s*:\s*(.+?)\s*$') { $wifiSsid = $matches[1].Trim() }
            if ($netshOut -match '(?im):\s*(\d{1,3})\s*%\s*$') {
                $sig = To-IntOrNull $matches[1]
                if ($null -ne $sig -and $sig -ge 0 -and $sig -le 100) { $wifiSignal = $sig }
            }
        }
    } catch { }
    # Hide VPN / virtual / Bluetooth pseudo adapters; they only add noise.
    $virtualPattern = '(?i)(virtual|vmware|hyper-v|vethernet|tap-|tailscale|radmin|zerotier|wireguard|hamachi|bluetooth|loopback|wan miniport|npcap|tap-windows|openvpn|sangfor|easyconnect)'
    $adapters = @()
    $wifiAssigned = $false
    foreach ($na in $netAdaptersRaw) {
        if ($null -eq $na) { continue }
        $nameVal = [string]$na.Name
        if ([string]::IsNullOrWhiteSpace($nameVal)) { continue }
        if ($nameVal -match $virtualPattern) { continue }
        $cfg = $null
        $idx = To-IntOrNull $na.Index
        if ($null -ne $idx -and $cfgByIndex.ContainsKey($idx)) { $cfg = $cfgByIndex[$idx] }
        if ($null -eq $cfg) {
            $macVal = [string]$na.MACAddress
            foreach ($c in $netConfigsRaw) {
                if ($null -ne $c -and [string]$c.MACAddress -eq $macVal) { $cfg = $c; break }
            }
        }
        $type = [string]$script:T.labels.other
        if ($nameVal -match '(?i)(wi-?fi|wlan|wireless|802\.11)') { $type = [string]$script:T.labels.wlan }
        elseif ([string]$na.AdapterType -match '(?i)ethernet' -or $nameVal -match '(?i)ethernet') { $type = [string]$script:T.labels.ethernet }
        $ipv4 = $null
        $ipv6 = $null
        $gateway = $null
        $dns = @()
        if ($null -ne $cfg) {
            foreach ($ip in @($cfg.IPAddress)) {
                $s = [string]$ip
                if ([string]::IsNullOrWhiteSpace($s)) { continue }
                if ($s -match '^\d{1,3}(\.\d{1,3}){3}$') {
                    if ($null -eq $ipv4) { $ipv4 = $s }
                } elseif ($s -match ':') {
                    if ($null -eq $ipv6) { $ipv6 = $s }
                }
            }
            foreach ($gw in @($cfg.DefaultIPGateway)) {
                $g = [string]$gw
                if (-not [string]::IsNullOrWhiteSpace($g)) { $gateway = $g; break }
            }
            foreach ($d in @($cfg.DNSServerSearchOrder)) {
                $ds = [string]$d
                if (-not [string]::IsNullOrWhiteSpace($ds)) { $dns += $ds }
            }
        }
        $speedMbps = $null
        $speedRaw = To-LongOrNull $na.Speed
        if ($null -ne $speedRaw -and $speedRaw -gt 0 -and $speedRaw -lt 100000000000) {
            $speedMbps = [long][Math]::Round($speedRaw / 1000000.0)
        }
        $status = To-IntOrNull $na.NetConnectionStatus
        $connected = ($status -eq 2)
        $ssid = $null
        $signal = $null
        if ($type -eq [string]$script:T.labels.wlan -and -not $wifiAssigned -and $connected) {
            $ssid = Clean-Text $wifiSsid
            $signal = $wifiSignal
            $wifiAssigned = $true
        }
        $adapters += [ordered]@{
            name      = $nameVal
            type      = $type
            mac       = Clean-Text $na.MACAddress
            ipv4      = $ipv4
            ipv6      = $ipv6
            gateway   = $gateway
            dns       = $dns
            speedMbps = $speedMbps
            connected = $connected
            ssid      = $ssid
            signalPct = $signal
        }
    }
    $network.adapters = $adapters
    # Internet reachability: ping with a 1.5s timeout, TCP 443 fallback, DNS capped at 1.5s.
    $internet = $null
    $latency = $null
    $pingOk = $false
    try {
        $ping = New-Object System.Net.NetworkInformation.Ping
        $reply = $ping.Send('223.5.5.5', 1500)
        if ($null -ne $reply -and [string]$reply.Status -eq 'Success') {
            $pingOk = $true
            $internet = $true
            $latency = [int]$reply.RoundtripTime
        }
    } catch { }
    if (-not $pingOk) {
        try {
            $client = New-Object System.Net.Sockets.TcpClient
            $ar = $client.BeginConnect('223.5.5.5', 443, $null, $null)
            if ($ar.AsyncWaitHandle.WaitOne(1500)) {
                $client.EndConnect($ar)
                $internet = $true
            } else {
                $internet = $false
            }
            $client.Close()
        } catch {
            $internet = $false
        }
    }
    $network.internet = $internet
    $network.latencyMs = $latency
    $dnsOk = $null
    try {
        $task = [System.Net.Dns]::BeginGetHostAddresses('www.baidu.com', $null, $null)
        if ($task.AsyncWaitHandle.WaitOne(1500)) {
            $addrs = [System.Net.Dns]::EndGetHostAddresses($task)
            $cnt = 0
            foreach ($a in $addrs) { $cnt++ }
            $dnsOk = ($cnt -gt 0)
        } else {
            $dnsOk = $false
        }
    } catch {
        $dnsOk = $false
    }
    $network.dnsOk = $dnsOk
    if ($internet -eq $false) { Add-Warn ([string]$script:T.warnings.networkProbe) }
    if ($dnsOk -eq $false) { Add-Warn ([string]$script:T.warnings.dnsProbe) }
} catch {
    Add-SectionFailure 'network' $_.Exception.Message
}
