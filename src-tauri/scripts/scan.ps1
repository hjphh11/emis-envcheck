# ---------- 1. Generic helpers ----------
function Add-Warn {
    param([string]$Message)
    if ([string]::IsNullOrWhiteSpace($Message)) { return }
    $m = $Message.Trim()
    if ($m.Length -gt 400) { $m = $m.Substring(0, 400) }
    if ($script:Warnings -notcontains $m -and $script:Warnings.Count -lt 40) { $script:Warnings += $m }
}

function Clean-Text {
    param($Value)
    if ($null -eq $Value) { return $null }
    $t = [string]$Value
    $t = $t.Trim()
    if ($t.Length -eq 0) { return $null }
    $placeholder = '^(?i)(n/?a|unknown|none|not available|not specified|default string|to be filled by o\.e\.m\.?|to be filled by oem|system serial number|system manufacturer|system product name|system version|oem|o\.e\.m\.|standard|base board|chassis manufacture|chassis serial number|asset tag|123456789|0|\.|-+)$'
    if ($t -match $placeholder) { return $null }
    return $t
}

function To-Num {
    param($Value)
    if ($null -eq $Value) { return $null }
    try { $d = [double]$Value } catch { return $null }
    if ([double]::IsNaN($d) -or [double]::IsInfinity($d)) { return $null }
    return $d
}

function To-IntOrNull {
    param($Value)
    $d = To-Num $Value
    if ($null -eq $d) { return $null }
    return [int][Math]::Round($d)
}

function To-LongOrNull {
    param($Value)
    $d = To-Num $Value
    if ($null -eq $d) { return $null }
    # Guard against values that would overflow Int64 (e.g. Win32_NetworkAdapter.Speed
    # reports 9223372036854775807 for "unknown" on some adapters). Note: the double
    # representation of Int64.MaxValue compares equal, hence >= / <= are required.
    if ($d -ge 9223372036854775807.0 -or $d -le -9223372036854775808.0) { return $null }
    return [long][Math]::Round($d)
}

function Clamp-Score {
    param([int]$Value)
    if ($Value -lt 0) { return 0 }
    if ($Value -gt 100) { return 100 }
    return $Value
}

function Format-Gb {
    param($Bytes)
    $d = To-Num $Bytes
    if ($null -eq $d) { return '0' }
    return ([string]([Math]::Round($d / 1073741824.0, 1)))
}

function Iso-Date {
    param($Value)
