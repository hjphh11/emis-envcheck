function Cim-Date {
    param($Value)
    if ($null -eq $Value) { return $null }
    # CIM DateTime properties arrive as [datetime] already; only raw strings need conversion.
    if ($Value -is [datetime]) { return $Value }
    if ($Value -is [datetimeoffset]) { return $Value.LocalDateTime }
    try {
        return [System.Management.ManagementDateTimeConverter]::ToDateTime([string]$Value)
    } catch {
        return $null
    }
}

