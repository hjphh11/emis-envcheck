# ---------- 3b. Display enumeration (user32 EnumDisplayDevices / EnumDisplaySettings) ----------
# Why: WmiMonitorID gives the EDID name/size but NOT the per-monitor current resolution,
# refresh rate or primary flag, and Win32_VideoController only reports the primary mode.
# user32 exposes all of that per DISPLAY device, and its monitor DeviceID contains the same
# EDID code (e.g. BOE0A1F / LEN62B5) found in WmiMonitorID.InstanceName, so they can be joined.
function Initialize-DisplayApi {
    if ('DispApi' -as [type]) { return $true }
    try {
        Add-Type -TypeDefinition @'
using System;
using System.Collections.Generic;
using System.Runtime.InteropServices;
public class DispApi {
    [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
    public struct DISPLAY_DEVICE {
        public int cb;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 32)] public string DeviceName;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 128)] public string DeviceString;
        public int StateFlags;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 128)] public string DeviceID;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 128)] public string DeviceKey;
    }
    [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
    public struct DEVMODE {
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 32)] public string dmDeviceName;
        public ushort dmSpecVersion;
        public ushort dmDriverVersion;
        public ushort dmSize;
        public ushort dmDriverExtra;
        public uint dmFields;
        public int dmPositionX;
        public int dmPositionY;
        public uint dmDisplayOrientation;
        public uint dmDisplayFixedOutput;
        public short dmColor;
        public short dmDuplex;
        public short dmYResolution;
        public short dmTTOption;
        public short dmCollate;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 32)] public string dmFormName;
        public ushort dmLogPixels;
        public uint dmBitsPerPel;
        public uint dmPelsWidth;
        public uint dmPelsHeight;
        public uint dmDisplayFlags;
        public uint dmDisplayFrequency;
        public uint dmICMMethod;
        public uint dmICMIntent;
        public uint dmMediaType;
        public uint dmDitherType;
        public uint dmReserved1;
        public uint dmReserved2;
        public uint dmPanningWidth;
        public uint dmPanningHeight;
    }
    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    public static extern bool EnumDisplayDevices(string lpDevice, uint iDevNum, ref DISPLAY_DEVICE lpDisplayDevice, uint dwFlags);
    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    public static extern bool EnumDisplaySettings(string lpszDeviceName, int iModeNum, ref DEVMODE lpDevMode);

    public static List<object[]> GetDisplays() {
        List<object[]> list = new List<object[]>();
        DISPLAY_DEVICE dd = new DISPLAY_DEVICE();
        dd.cb = Marshal.SizeOf(typeof(DISPLAY_DEVICE));
        for (uint i = 0; EnumDisplayDevices(null, i, ref dd, 0); i++) {
            if ((dd.StateFlags & 0x1) == 0) {
                dd.cb = Marshal.SizeOf(typeof(DISPLAY_DEVICE));
                continue;
            }
            DEVMODE dm = new DEVMODE();
            dm.dmSize = (ushort)Marshal.SizeOf(typeof(DEVMODE));
            bool ok = EnumDisplaySettings(dd.DeviceName, -1, ref dm);
            string monitorName = "";
            string monitorId = "";
            DISPLAY_DEVICE md = new DISPLAY_DEVICE();
            md.cb = Marshal.SizeOf(typeof(DISPLAY_DEVICE));
            if (EnumDisplayDevices(dd.DeviceName, 0, ref md, 1)) {
                monitorName = md.DeviceString;
                monitorId = md.DeviceID;
            }
            list.Add(new object[] {
                dd.DeviceName,
                dd.DeviceString,
                (dd.StateFlags & 0x4) != 0,
                ok ? (int)dm.dmPelsWidth : 0,
                ok ? (int)dm.dmPelsHeight : 0,
                ok ? (int)dm.dmDisplayFrequency : 0,
                monitorName,
                monitorId
            });
            dd.cb = Marshal.SizeOf(typeof(DISPLAY_DEVICE));
        }
        return list;
    }
}
'@ -ErrorAction Stop
        return $true
    } catch {
        return $false
    }
}

function Get-DisplayDevices {
    if (-not (Initialize-DisplayApi)) { return $null }
    try {
        $raw = [DispApi]::GetDisplays()
    } catch {
        return $null
    }
    $out = @()
    foreach ($row in $raw) {
        if ($null -eq $row) { continue }
        $out += [ordered]@{
            deviceName  = [string]$row[0]
            adapterName = [string]$row[1]
            primary     = [bool]$row[2]
            width       = To-IntOrNull $row[3]
            height      = To-IntOrNull $row[4]
            refreshHz   = To-IntOrNull $row[5]
            monitorName = [string]$row[6]
            monitorId   = [string]$row[7]
        }
    }
    return $out
}

