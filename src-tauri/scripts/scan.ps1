                (dd.StateFlags & 0x4) != 0,
                ok ? (int)dm.dmPelsWidth : 0,
                ok ? (int)dm.dmPelsHeight : 0,
                ok ? (int)dm.dmDisplayFrequency : 0,
                monitorName,
                monitorId
            });
            dd.cb = Marshal.SizeOf(typeof(DISPLAY_DEVICE));
        }
        return list;
    }
}
'@ -ErrorAction Stop
        return $true
    } catch {
        return $false
    }
}

function Get-DisplayDevices {
    if (-not (Initialize-DisplayApi)) { return $null }
    try {
        $raw = [DispApi]::GetDisplays()
    } catch {
        return $null
    }
    $out = @()
    foreach ($row in $raw) {
        if ($null -eq $row) { continue }
        $out += [ordered]@{
            deviceName  = [string]$row[0]
            adapterName = [string]$row[1]
            primary     = [bool]$row[2]
            width       = To-IntOrNull $row[3]
            height      = To-IntOrNull $row[4]
            refreshHz   = To-IntOrNull $row[5]
            monitorName = [string]$row[6]
            monitorId   = [string]$row[7]
        }
    }
    return $out
}

