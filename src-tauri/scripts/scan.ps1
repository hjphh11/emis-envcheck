        foreach ($p in $cpuList) {
            if ($null -eq $p) { continue }
            if ($null -eq $first) { $first = $p }
            $c = To-IntOrNull $p.NumberOfCores
            if ($null -ne $c) { $cores += $c }
            $threadCount = To-IntOrNull $p.NumberOfLogicalProcessors
            if ($null -ne $threadCount) { $threads += $threadCount }
            $mc = To-IntOrNull $p.MaxClockSpeed
            if ($null -ne $mc -and $mc -gt $maxClock) { $maxClock = $mc }
            $c2 = To-IntOrNull $p.L2CacheSize
            if ($null -ne $c2) { $l2 += $c2 }
            $c3 = To-IntOrNull $p.L3CacheSize
            if ($null -ne $c3) { $l3 += $c3 }
            $ld = To-IntOrNull $p.LoadPercentage
            if ($null -ne $ld) { $loads += $ld }
        }
        if ($null -ne $first) {
            $brandName = Clean-Text $first.Name
            if ($null -ne $brandName) { $cpu.brand = $brandName }
            $mfr = [string]$first.Manufacturer
            if ($mfr -match '(?i)intel') { $cpu.vendor = 'Intel' }
            elseif ($mfr -match '(?i)amd') { $cpu.vendor = 'AMD' }
            elseif ($mfr) { $cpu.vendor = Clean-Text $mfr }
            if ($cores -gt 0) { $cpu.physicalCores = $cores }
            if ($threads -gt 0) { $cpu.logicalCores = $threads }
            if ($maxClock -gt 0) { $cpu.baseMhz = $maxClock }
            if ($l2 -gt 0) { $cpu.l2Bytes = [long]$l2 * 1024 }
            if ($l3 -gt 0) { $cpu.l3Bytes = [long]$l3 * 1024 }
            $cpu.socket = Clean-Text $first.SocketDesignation
            $addrWidth = To-IntOrNull $first.AddressWidth
            if ($null -ne $addrWidth) {
                if ($addrWidth -ge 64) { $cpu.arch = 'x64' } else { $cpu.arch = 'x86' }
            }
            $virtFw = $null
            if ($null -ne $first.VirtualizationFirmwareEnabled) { $virtFw = [bool]$first.VirtualizationFirmwareEnabled }
            if ($null -ne $csInfo -and $csInfo.HypervisorPresent -eq $true) { $cpu.virtualization = $true }
            else { $cpu.virtualization = $virtFw }
            if ($loads.Count -gt 0) {
                $sum = 0
                foreach ($l in $loads) { $sum += $l }
                $cpu.usagePct = [int][Math]::Round($sum / $loads.Count)
            }
        }
    } else {
        # Registry fallback when WMI is unavailable.
        $regCpu = Get-RegItem 'HKLM:\HARDWARE\DESCRIPTION\System\CentralProcessor\0'
        if ($null -ne $regCpu) {
            $name = Clean-Text $regCpu.ProcessorNameString
            if ($null -ne $name) { $cpu.brand = $name }
            $mhz = To-IntOrNull $regCpu.'~MHz'
            if ($null -ne $mhz) { $cpu.baseMhz = $mhz; $cpu.currentMhz = $mhz }
            if ([string]$regCpu.Identifier -match '(?i)intel') { $cpu.vendor = 'Intel' }
            else { $cpu.vendor = 'AMD' }
        }
        Add-Warn ([string]$script:T.warnings.cpuFallback)
    }
    $regCpu0 = Get-RegItem 'HKLM:\HARDWARE\DESCRIPTION\System\CentralProcessor\0'
    if ($null -ne $regCpu0) {
        $cur = To-IntOrNull $regCpu0.'~MHz'
        if ($null -ne $cur -and $cur -gt 0) { $cpu.currentMhz = $cur }
    }
    # Instruction set via kernel32.IsProcessorFeaturePresent (readable by standard users).
    $featOk = Initialize-CpuFeatures
    $script:CpuFeaturesOk = $featOk
    $instr = @()
    if ($featOk) {
        if (Test-CpuFeature 6)  { $instr += 'SSE' }
        if (Test-CpuFeature 10) { $instr += 'SSE2' }
        if (Test-CpuFeature 13) { $instr += 'SSE3' }
        if (Test-CpuFeature 36) { $instr += 'SSSE3' }
        if (Test-CpuFeature 37) { $instr += 'SSE4.1' }
        if (Test-CpuFeature 38) { $instr += 'SSE4.2' }
        if (Test-CpuFeature 39) { $instr += 'AVX' }
        if (Test-CpuFeature 40) { $instr += 'AVX2' }
        if (Test-CpuFeature 41) { $instr += 'AVX512F' }
        # POPCNT shares the CPUID feature bit family with SSE4.2; every SSE4.2 CPU has it.
        if ($instr -contains 'SSE4.2') { $instr += 'POPCNT' }
    }
    $cpu.instructions = $instr
} catch {
    Add-SectionFailure 'cpu' $_.Exception.Message
}
