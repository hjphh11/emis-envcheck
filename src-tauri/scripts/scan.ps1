$memory = [ordered]@{
    totalBytes = 0; availableBytes = 0; usedBytes = 0; usedPct = 0
    modules = @(); dualChannelHint = $null
}
$swSec = Start-Timer
try {
    $total = $null
    if ($null -ne $csInfo) { $total = To-LongOrNull $csInfo.TotalPhysicalMemory }
    if (($null -eq $total -or $total -le 0) -and $null -ne $osInfo) {
        $tv = To-LongOrNull $osInfo.TotalVisibleMemorySize
        if ($null -ne $tv) { $total = $tv * 1024 }
    }
    $avail = $null
    if ($null -ne $osInfo) {
        $fp = To-LongOrNull $osInfo.FreePhysicalMemory
        if ($null -ne $fp) { $avail = $fp * 1024 }
    }
    if ($null -ne $total -and $total -gt 0) {
        $memory.totalBytes = [long]$total
        if ($null -ne $avail -and $avail -ge 0) {
            if ($avail -gt $total) { $avail = $total }
            $memory.availableBytes = [long]$avail
        }
        $used = $memory.totalBytes - $memory.availableBytes
        if ($used -lt 0) { $used = 0 }
        $memory.usedBytes = [long]$used
        $memory.usedPct = [double][Math]::Round(($used * 100.0) / $memory.totalBytes, 1)
    }
    $modules = @()
    foreach ($m in $memModulesRaw) {
        if ($null -eq $m) { continue }
        $typeName = $null
        $tcode = To-IntOrNull $m.SMBIOSMemoryType
        if ($null -ne $tcode) {
            $map = @{ 20 = 'DDR'; 21 = 'DDR2'; 22 = 'DDR2 FB-DIMM'; 24 = 'DDR3'; 26 = 'DDR4'; 27 = 'LPDDR'; 28 = 'LPDDR2'; 29 = 'LPDDR3'; 30 = 'LPDDR4'; 34 = 'DDR5'; 35 = 'LPDDR5' }
            if ($map.ContainsKey($tcode)) { $typeName = $map[$tcode] }
        }
        $formName = $null
        $fcode = To-IntOrNull $m.FormFactor
        if ($null -ne $fcode) {
            $fmap = @{ 8 = 'DIMM'; 12 = 'SODIMM'; 13 = 'SRIMM'; 16 = 'FB-DIMM' }
            if ($fmap.ContainsKey($fcode)) { $formName = $fmap[$fcode] }
        }
        $modules += [ordered]@{
            slot          = Clean-Text $m.DeviceLocator
            manufacturer  = Clean-Text $m.Manufacturer
            partNumber    = Clean-Text $m.PartNumber
            serial        = Clean-Text $m.SerialNumber
            capacityBytes = To-LongOrNull $m.Capacity
            ratedMhz      = To-IntOrNull $m.Speed
            speedMhz      = To-IntOrNull $m.ConfiguredClockSpeed
            type          = $typeName
            formFactor    = $formName
            voltageMv     = To-IntOrNull $m.ConfiguredVoltage
        }
    }
    $memory.modules = $modules
    if ($modules.Count -ge 2) {
        $firstCap = $modules[0].capacityBytes
        $symmetric = $true
        foreach ($mo in $modules) {
            if ($null -ne $firstCap -and $mo.capacityBytes -ne $firstCap) { $symmetric = $false }
        }
        $memory.dualChannelHint = $symmetric
    } elseif ($modules.Count -eq 1) {
        $memory.dualChannelHint = $false
    }
    if ($memory.totalBytes -eq 0) {
        Add-SectionFailure 'memory' 'TotalPhysicalMemory unavailable'
    }
} catch {
    Add-SectionFailure 'memory' $_.Exception.Message
}
Stop-Timer 'memory' $swSec

# ---------- 11. gpus ----------
$gpus = @()
$swSec = Start-Timer
try {
    # VRAM: prefer the display class registry HardwareInformation.qwMemorySize.
    # Win32_VideoController.AdapterRAM is UInt32 and saturates/overflows above 4GB.
    # Read via the .NET registry API: the PowerShell provider can deny enumeration of this
    # key for standard users even though opening the individual subkeys is allowed.
    $vramMap = @{}
    try {
        $classKey = [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey('SYSTEM\CurrentControlSet\Control\Class\{4d36e968-e325-11ce-bfc1-08002be10318}')
        if ($null -ne $classKey) {
            foreach ($subName in $classKey.GetSubKeyNames()) {
                if ($subName -notmatch '^\d{4}$') { continue }
                $subKey = $classKey.OpenSubKey($subName)
                if ($null -eq $subKey) { continue }
                $desc = Clean-Text $subKey.GetValue('DriverDesc')
                $qw = $subKey.GetValue('HardwareInformation.qwMemorySize')
                if ($null -ne $desc) { $vramMap[$desc] = To-LongOrNull $qw }
                $subKey.Close()
            }
            $classKey.Close()
        }
    } catch { }
    foreach ($vc in $videoList) {
        if ($null -eq $vc) { continue }
        $name = Clean-Text $vc.Name
        if ($null -eq $name) { continue }
        $vram = $null
        if ($vramMap.ContainsKey($name)) { $vram = $vramMap[$name] }
        if ($null -eq $vram -or $vram -le 0) {
            $adapterRam = To-LongOrNull $vc.AdapterRAM
            if ($null -ne $adapterRam -and $adapterRam -gt 0 -and $adapterRam -lt 4000000000) { $vram = $adapterRam } else { $vram = $null }
        }
        $vendor = $null
        $pnp = [string]$vc.PNPDeviceID
        if ($pnp -match '(?i)VEN_10DE') { $vendor = 'NVIDIA' }
        elseif ($pnp -match '(?i)VEN_1002|VEN_1022') { $vendor = 'AMD' }
        elseif ($pnp -match '(?i)VEN_8086') { $vendor = 'Intel' }
        elseif ($pnp -match '(?i)VEN_1A03') { $vendor = 'ASPEED' }
        $discrete = $null
        if ($name -match '(?i)(geforce|rtx|gtx|radeon\s*rx|radeon\s*pro|quadro|arc\s*[ab])') { $discrete = $true }
        elseif ($name -match '(?i)(intel.*(uhd|hd|iris)|radeon.*(vega|graphics)|microsoft basic|remote display)') { $discrete = $false }
        $drvDate = Cim-Date $vc.DriverDate
        $gpus += [ordered]@{
            name          = $name
            vendor        = $vendor
            vramBytes     = $vram
            driverVersion = Clean-Text $vc.DriverVersion
            driverDate    = $(if ($null -ne $drvDate) { Iso-Date $drvDate } else { $null })
            discrete      = $discrete
            status        = Clean-Text $vc.Status
        }
    }
    if ($gpus.Count -eq 0) { Add-Warn ([string]$script:T.warnings.noGpu) }
} catch {
    Add-SectionFailure 'gpu' $_.Exception.Message
}
Stop-Timer 'gpu' $swSec

# ---------- 12. displays ----------
$displays = @()
